"use strict";
// The duplicate-code detector (1.28) — synthetic projects, spec_scan {duplicates}, finish's warning, the plugin's own sources.

const fs = require("fs");
const path = require("path");

exports.run = async ({ ok, all, rpc, payload, S, root, tmp, libSources }) => {
  const js = (v) => JSON.stringify(v);
  const call = (name, args) => rpc("tools/call", { name, arguments: args });
  const write = (dir, rel, text) => { fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true }); fs.writeFileSync(path.join(dir, rel), text); };
  const at = (d) => d.file + ":" + d.from + "-" + d.to;
  // a helper the project already has — nine code lines, comments and blank lines around them
  const HELPER = [
    "function formatPrice(cents, currency, locale) {",
    "  const amount = Math.round(Number(cents)) / 100;",
    "  if (!Number.isFinite(amount)) throw new Error(\"not a price: \" + cents);",
    "  const opts = { style: \"currency\", currency: currency || \"EUR\" };",
    "  const text = new Intl.NumberFormat(locale || \"en\", opts).format(amount);",
    "  const sign = amount < 0 ? \"-\" : \"\";",
    "  const parts = text.replace(\"-\", \"\").split(\" \").filter(Boolean);",
    "  const joined = parts.map((p) => p.trim()).join(\" \");",
    "  return sign + joined;",
    "}",
  ];
  // a block the feature writes twice (its own files) — nine code lines
  const RECEIPT = [
    "function receiptLines(order) {",
    "  const lines = order.items.map((it) => it.name + \" x\" + it.qty);",
    "  const subtotal = order.items.reduce((s, it) => s + it.price * it.qty, 0);",
    "  const shipping = subtotal > 5000 ? 0 : order.shippingCents || 499;",
    "  const discount = order.coupon ? Math.min(order.coupon.cents, subtotal) : 0;",
    "  lines.push(\"subtotal \" + subtotal, \"shipping \" + shipping);",
    "  if (discount) lines.push(\"discount -\" + discount);",
    "  lines.push(\"total \" + (subtotal + shipping - discount));",
    "  return lines;",
    "}",
  ];
  const TASKS = (...files) => "# Tasks\n\n- [ ] 1. [US1] Build it\n  - _Requirements: US-1.AC-1_\n" + files.map((f) => "  - _Implements: " + f + "_\n").join("");

  // --- the detector on a synthetic JS project: existing / within, comments ignored, strings kept, tests out by default ---
  const dp = path.join(tmp, "proj-dupes-js");
  S.initProject(dp, ["core"], "en");
  const cf = S.createFeature(dp, "Checkout", ["core"], "Checkout");
  write(dp, "src/lib/money.js", "\"use strict\";\n// Money helpers.\n\n" + HELPER.join("\n") + "\n\nmodule.exports = { formatPrice };\n");
  // the feature's copy: other comments, other indentation, a block comment and blank lines in the middle (lines 6–19)
  write(dp, "src/checkout/total.js", "// the order's total\nconst lib = require(\"../lib/money\");\nconst TAX_RATE = 0.23;\n\n\n" +
    HELPER.slice(0, 4).map((l) => "    " + l.trim() + "   // copied").join("\n") + "\n  /* why: the\n     format we print */\n\n" + HELPER.slice(4).join("\n") +
    "\n\n" + RECEIPT.join("\n") + "\nmodule.exports = { formatPrice, receiptLines };\n");
  write(dp, "src/checkout/receipt.js", "\"use strict\";\n\n" + RECEIPT.join("\n") + "\nmodule.exports = { receiptLines };\n");
  // the same shape with OTHER strings — no duplicate (two blocks that differ only in their strings are different code)
  write(dp, "src/lib/labels.js", HELPER.map((l) => l.replace(/"([^"]*)"/g, (m, s) => "\"" + (s ? s.toUpperCase() + "!" : "?") + "\"")).join("\n") + "\n");
  // a test file holding the helper: left out unless tests: true
  write(dp, "tests/money.test.js", HELPER.join("\n") + "\nmodule.exports = {};\n");
  // generated / minified copies: never read
  write(dp, "src/gen/money.min.js", HELPER.join("\n") + "\n");
  write(dp, "src/gen/money_pb.js", "// Code generated by protoc-gen-js. DO NOT EDIT.\n" + HELPER.join("\n") + "\n");
  fs.writeFileSync(path.join(cf.dir, "tasks.md"), TASKS("src/checkout/total.js", "src/checkout/receipt.js"));

  const fr = S.duplicationReport(dp, { name: "checkout" });
  const ex = fr.duplicates.filter((d) => d.kind === "existing"), wi = fr.duplicates.filter((d) => d.kind === "within");
  const all1 = S.duplicationReport(dp, {});
  const withTests = S.duplicationReport(dp, { name: "checkout", tests: true });
  const named = (r) => r.duplicates.flatMap((d) => [d.file, ...d.also.map((a) => a.file)]);
  all("1.28 dupes: a feature's copy of an existing helper (other comments, indentation, a block comment and blank lines inside) is ONE `existing` run — its file:lines and the helper's; the block its two files share is `within`, listed once; a block differing only in its strings is no duplicate; a test, a .min.js and a 'Code generated … DO NOT EDIT' copy are never read (tests: true adds the test file); stable keys (got " +
    js({ ex, wi, counts: fr.counts, skipped: fr.skipped, scanned: fr.scanned, project: all1.duplicates.map((d) => d.kind + " " + at(d)) }) + ")", {
    ok: () => fr.ok === true && fr.feature === "checkout" && fr.minLines === 6 && fr.featureFiles === 2 && fr.truncated === false,
    keys: () => js(Object.keys(fr)) === js(["ok", "feature", "minLines", "featureFiles", "scanned", "skipped", "truncated", "duplicates", "counts", "total"]),
    existing: () => ex.length === 1 && ex[0].file === "src/checkout/total.js" && ex[0].from === 6 && ex[0].to === 17 && ex[0].lines === 9 &&
      js(ex[0].also) === js([{ file: "src/lib/money.js", from: 4, to: 12 }]),
    within: () => wi.length === 1 && [wi[0].file, wi[0].also[0].file].sort().join() === "src/checkout/receipt.js,src/checkout/total.js" && wi[0].lines === 9,
    counts: () => js(fr.counts) === js({ existing: 1, within: 1 }) && fr.total === 2 && fr.duplicates[0].kind === "existing",
    entryKeys: () => js(Object.keys(ex[0])) === js(["kind", "file", "from", "to", "lines", "also"]),
    stringsKept: () => !named(all1).includes("src/lib/labels.js"),
    noTests: () => !named(fr).includes("tests/money.test.js") && !named(all1).includes("tests/money.test.js"),
    testsOn: () => named(withTests).includes("tests/money.test.js") && withTests.counts.existing === 1 && withTests.duplicates[0].also.length === 2,
    generated: () => fr.skipped.generated === 2 && !named(all1).some((f) => f.startsWith("src/gen/")),
    project: () => all1.feature === undefined && all1.featureFiles === undefined && all1.duplicates.every((d) => d.kind === "within") && all1.counts.existing === 0 &&
      all1.duplicates.some((d) => [d.file, ...d.also.map((a) => a.file)].includes("src/lib/money.js")),
    deterministic: () => js(S.duplicationReport(dp, { name: "checkout" })) === js(fr) && js(S.duplicationReport(dp, {})) === js(all1),
  });

  // minLines: a five-line repeat is found with minLines 4 (4–100), never with the default 6; the cap → truncated, a feature's own files
  // read all the same; a feature naming no file of its own reads nothing; an unknown feature is refused
  {
    const FIVE = ["const width = Number(options.width || 80);", "const height = Number(options.height || 24);", "const area = width * height * options.scale;",
      "const label = options.title + \" — \" + area;", "console.log(label.padEnd(width, \".\"));"];
    write(dp, "src/lib/five-a.js", "function a(options) {\n" + FIVE.join("\n") + "\n}\n");
    write(dp, "src/lib/five-b.js", "function b(options) {\n" + FIVE.join("\n") + "\n}\n");
    const r4 = S.duplicationReport(dp, { minLines: 4 }), r8 = S.duplicationReport(dp, {});
    const five = (r) => r.duplicates.some((d) => [d.file, ...d.also.map((a) => a.file)].join().includes("five-"));
    const capped = S.duplicationReport(dp, { name: "checkout", cap: 1 });
    const none = S.createFeature(dp, "Empty", ["core"], "x");
    const nr = S.duplicationReport(dp, { name: "empty" });
    const unknown = S.duplicationReport(dp, { name: "nope" });
    all("1.28 dupes: minLines 4 finds a five-line repeat the default 6 doesn't (an out-of-range value is the default); past the file cap `truncated`, the feature's own files still read; a feature whose _Implements:_ name no file reads nothing (featureFiles 0); an unknown feature is feature-not-found (got " +
      js({ r4: r4.counts, r8: r8.counts, capped: [capped.truncated, capped.featureFiles, capped.counts], nr, unknown: unknown.code }) + ")", {
      four: () => r4.minLines === 4 && five(r4) && !five(r8) && S.duplicationReport(dp, { minLines: 3 }).minLines === 6,
      cap: () => capped.truncated === true && capped.featureFiles === 2 && capped.counts.within === 1,
      empty: () => none.ok !== false && nr.ok === true && nr.featureFiles === 0 && nr.scanned.files === 0 && nr.total === 0,
      unknown: () => unknown.ok === false && unknown.code === "feature-not-found",
    });
  }

  // other languages: Python (# comments), SQL (-- and /* */), CRLF + a BOM — the line numbers are the file's own
  {
    const lp = path.join(tmp, "proj-dupes-langs");
    S.initProject(lp, ["core"], "en");
    const PY = ["def normalize_rows(rows, limit=100):", "    out = [r.strip() for r in rows if r and r.strip()]", "    if len(out) > limit:",
      "        raise ValueError(\"too many rows: %d\" % len(out))", "    seen = set()", "    unique = []", "    for r in out:",
      "        if r in seen:", "            continue", "        seen.add(r)", "        unique.append(r)", "    return unique"];
    write(lp, "pkg/a.py", "# module a\n" + PY.join("\n") + "\n");
    write(lp, "pkg/b.py", "import os\n\n" + PY.map((l, i) => (i % 3 === 0 ? l + "  # note " + i : l)).join("\n") + "\n");
    const SQL = ["SELECT o.id, o.customer_id, o.total_cents", "FROM orders o", "JOIN customers c ON c.id = o.customer_id",
      "WHERE o.status = 'paid' AND o.created_at > now() - interval '30 days'", "AND c.country IN ('PT', 'ES', 'FR')", "GROUP BY o.id, o.customer_id, o.total_cents",
      "HAVING SUM(o.total_cents) > 10000", "ORDER BY o.total_cents DESC", "LIMIT 100;"];
    write(lp, "db/report.sql", "-- the monthly report\n" + SQL.join("\n") + "\n");
    write(lp, "db/export.sql", "/* the export\n   reuses the report */\n" + SQL.map((l) => l + " -- x").join("\n") + "\n");
    const LINES = HELPER.join("\n");
    write(lp, "src/a.js", LINES + "\n");
    fs.writeFileSync(path.join(lp, "src", "b.js"), String.fromCharCode(0xfeff) + "\r\n\r\n\r\n" + HELPER.join("\r\n") + "\r\n");
    const r = S.duplicationReport(lp, {});
    const pair = (a, b) => r.duplicates.find((d) => (d.file === a && d.also[0].file === b) || (d.file === b && d.also[0].file === a));
    const py = pair("pkg/a.py", "pkg/b.py"), sql = pair("db/export.sql", "db/report.sql"), crlf = pair("src/a.js", "src/b.js");
    const bSide = crlf && (crlf.file === "src/b.js" ? crlf : { file: "src/b.js", from: crlf.also[0].from, to: crlf.also[0].to });
    all("1.28 dupes: language-agnostic — a Python function with # comments added, an SQL query with -- and /* */ comments, and a CRLF + BOM copy are each one run; the copy's line numbers are its own (the BOM shifts nothing; got " +
      js({ py, sql, crlf, counts: r.counts }) + ")", {
      python: () => !!py && py.lines === 12,
      sql: () => !!sql && sql.lines === 9,
      crlfBom: () => !!crlf && crlf.lines === 9 && bSide.from === 4 && bSide.to === 12,
    });
  }

  // --- the MCP mode: spec_scan {duplicates: true} is the engine's call; another mode's argument is refused ---
  {
    const viaMcp = payload(await call("spec_scan", { projectDir: dp, duplicates: true, name: "checkout" }));
    const proj = payload(await call("spec_scan", { projectDir: dp, duplicates: true, coverage: false, minLines: 4, tests: true }));
    const capped = await call("spec_scan", { projectDir: dp, duplicates: true, cap: 5 });
    const nameScan = await call("spec_scan", { projectDir: dp, name: "checkout" });
    const both = await call("spec_scan", { projectDir: dp, duplicates: true, coverage: true });
    const off = payload(await call("spec_scan", { projectDir: dp, duplicates: false, cap: 50 }));
    const small = await call("spec_scan", { projectDir: dp, duplicates: true, minLines: 3 });
    const big = await call("spec_scan", { projectDir: dp, duplicates: true, minLines: 101 });
    const p = (res) => JSON.parse(res.result.content[0].text);
    all("1.28 spec_scan {duplicates: true}: the engine's report (name, minLines, tests); cap is the inventory's (inapplicable-arguments), name without duplicates too, coverage: true beside it is another mode; duplicates: false is the inventory; minLines 4–100 (got " +
      js({ capped: p(capped), nameScan: p(nameScan), both: p(both), small: p(small).code, big: p(big).code, off: off.filesScanned }) + ")", {
      same: () => js(viaMcp) === js(S.duplicationReport(dp, { name: "checkout" })),
      project: () => js(proj) === js(S.duplicationReport(dp, { minLines: 4, tests: true })),
      cap: () => capped.result.isError && p(capped).code === "inapplicable-arguments" && js(p(capped).inapplicable) === js(["cap"]),
      name: () => nameScan.result.isError && p(nameScan).code === "inapplicable-arguments" && js(p(nameScan).inapplicable) === js(["name"]),
      both: () => both.result.isError && js(p(both).inapplicable) === js(["coverage"]),
      off: () => off.ok === true && typeof off.filesScanned === "number" && off.duplicates === undefined,
      bounds: () => small.result.isError && p(small).code === "invalid-arguments" && big.result.isError && p(big).code === "invalid-arguments",
    });
  }

  // --- spec_finish: a warning (never a blocker) naming how many places, the top 3, the call that lists them; EN / PT / ES ---
  {
    const L = {
      en: [/the feature's code repeats existing code in 1 place\(s\) — src\/checkout\/total\.js:6-17 ↔ src\/lib\/money\.js:4-12: reuse or extend the existing code/, /1 more repeat\(s\) inside the feature's own files/],
      pt: [/o código da feature repete código existente em 1 sítio\(s\) — src\/checkout\/total\.js:6-17 ↔ src\/lib\/money\.js:4-12: reutilizar ou estender/, /mais 1 repetição\(ões\) dentro dos ficheiros da própria feature/],
      es: [/el código de la función repite código existente en 1 lugar\(es\) — src\/checkout\/total\.js:6-17 ↔ src\/lib\/money\.js:4-12: reutilizar o extender/, /1 repetición\(es\) más dentro de los ficheros de la propia función/],
    };
    const got = {};
    for (const lang of Object.keys(L)) {
      const fp = path.join(tmp, "proj-dupes-finish-" + lang);
      S.initProject(fp, ["core"], lang);
      const f = S.createFeature(fp, "Checkout", ["core"], "x");
      for (const rel of ["src/lib/money.js", "src/checkout/total.js", "src/checkout/receipt.js"]) write(fp, rel, fs.readFileSync(path.join(dp, rel), "utf8"));
      fs.writeFileSync(path.join(f.dir, "tasks.md"), TASKS("src/checkout/total.js", "src/checkout/receipt.js"));
      const fin = payload(await call("spec_finish", { projectDir: fp, name: f.slug }));
      got[lang] = { warn: (fin.warnings || []).find((w) => /dupes/.test(w)), dup: fin.duplicates, blockers: fin.blockers };
    }
    const en = got.en;
    all("1.28 spec_finish: the feature's code repeating existing code is a WARNING — how many places, the top 3 as file:from-to ↔ file:from-to, the inside-the-feature repeats as a count, the call that lists them all (spec_scan {duplicates: true, name} · dev-spec dupes) — EN / PT / ES; `duplicates` {existing, within, top}; never a blocker (got " +
      js(got) + ")", {
      ...Object.fromEntries(Object.keys(L).map((lang) => [lang, () => !!got[lang].warn && L[lang].every((re) => re.test(got[lang].warn)) &&
        got[lang].warn.includes("spec_scan {duplicates: true, name: \"checkout\"}") && /dupes checkout\)$/.test(got[lang].warn)])),
      key: () => en.dup.existing === 1 && en.dup.within === 1 && en.dup.top.length === 1 && en.dup.top[0].file === "src/checkout/total.js",
      noBlocker: () => !en.blockers.some((b) => /repeat|dupes/.test(b)),
    });
    // only repeats inside the feature: the count alone; no repeat at all: no warning, no key
    const wp = path.join(tmp, "proj-dupes-finish-within");
    S.initProject(wp, ["core"], "en");
    const wf = S.createFeature(wp, "Receipts", ["core"], "x");
    write(wp, "src/r1.js", RECEIPT.join("\n") + "\n");
    write(wp, "src/r2.js", RECEIPT.join("\n") + "\n");
    fs.writeFileSync(path.join(wf.dir, "tasks.md"), TASKS("src/r1.js", "src/r2.js"));
    const w1 = payload(await call("spec_finish", { projectDir: wp, name: wf.slug }));
    fs.writeFileSync(path.join(wf.dir, "tasks.md"), TASKS("src/r1.js"));
    write(wp, "src/r2.js", "module.exports = {};\n");
    const w0 = payload(await call("spec_finish", { projectDir: wp, name: wf.slug }));
    const wWarn = (w1.warnings || []).find((w) => /dupes/.test(w));
    ok(/^1 block\(s\) of the feature's code repeat another place in its own files — a candidate for the simplification pass/.test(wWarn || "") &&
      js(w1.duplicates) === js({ existing: 0, within: 1, top: [] }) && w0.duplicates === undefined && !(w0.warnings || []).some((w) => /dupes/.test(w)),
      "1.28 spec_finish: repeats inside the feature only → one warning with the count (the simplification pass's); none → no warning and no `duplicates` key (got " + js([wWarn, w1.duplicates, w0.duplicates]) + ")");
  }

  // --- duplicateRuns over texts: `code` (the run's normalized lines — what an allow-list reads) and scanned.duplicated (the lines in a
  // repeated window, both sides) ---
  {
    const r = S.duplicateRuns([{ file: "a.js", text: "// a\n" + HELPER.join("\n") + "\n" }, { file: "b.js", text: HELPER.map((l) => "    " + l + "  /* b */").join("\n") + "\n" }], { code: true });
    const plain = S.duplicateRuns([{ file: "a.js", text: HELPER.join("\n") }, { file: "b.js", text: HELPER.join("\n") }]);
    ok(r.duplicates.length === 1 && js(r.duplicates[0].code) === js(HELPER.slice(0, 9).map((l) => l.trim())) && r.scanned.duplicated === 18 && r.scanned.lines === 18 &&
      plain.duplicates[0].code === undefined && plain.scanned.duplicated === 18,
      "1.28 duplicateRuns: {code: true} gives each run its normalized lines (comments out, whitespace folded); scanned.duplicated counts the code lines in a repeated window on both sides (got " +
      js([r.duplicates, r.scanned, plain.scanned]) + ")");
  }

  // --- the two entry points agree: duplicationReport walking a folder (mcp/lib) = duplicateRuns over the same files read by hand
  // (libSources()) — the call 16-conventions-duplication.js, the plugin's own duplication guard, makes over all its sources ---
  {
    const lib = path.join(root, "mcp", "lib");
    const rep = S.duplicationReport(lib, { minLines: 8 });
    const files = libSources().map((f) => ({ file: path.relative(lib, f).split(path.sep).join("/"), text: fs.readFileSync(f, "utf8") }));
    const runs = S.duplicateRuns(files, { minLines: 8 });
    ok(rep.ok === true && rep.scanned.files >= 40 && rep.truncated === false && js(runs.scanned) === js(rep.scanned) && js(runs.counts) === js(rep.counts) &&
      js(runs.duplicates.slice(0, 20)) === js(rep.duplicates) && rep.counts.existing === 0 && rep.scanned.duplicated <= rep.scanned.lines,
      "1.28: duplicationReport over a folder (this repo's mcp/lib, minLines 8) = duplicateRuns over the same files read by hand — " + rep.scanned.files + " files, " +
      rep.scanned.lines + " code lines, " + rep.total + " repeated block(s) (got " + js([rep.scanned, rep.counts, runs.scanned, runs.counts]) + ")");
  }
};

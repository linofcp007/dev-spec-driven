"use strict";
// Guards and hooks — 1.27: the project probe (mcp/lib/probe.js), ONE dev-spec project rule — the hooks, the engine and the status line agree on every layout.
// (Until 1.26 four copies of "is this a dev-spec .specs/?" disagreed: a classified feature alone was a project to the Stop and observe
// hooks but not to the edit guard or the status line; a generated ROADMAP.md counted for two hooks; the guard took the nearest .specs/
// of any tool and missed the dev-spec project above it.)

const fs = require("fs");
const path = require("path");
const { spawn, spawnSync } = require("child_process");

exports.run = async ({ ok, all, S, tmp, __dirname, require }) => {
  const js = JSON.stringify;
  const P = require("./lib/probe.js");
  const HU = require("../hooks/hook-utils.js");
  const C = require("../cli/completion.js");
  const HOOKS = path.join(__dirname, "..", "hooks");
  const BS = String.fromCharCode(92);
  const WIN = process.platform === "win32";
  const base = path.join(tmp, "probe");
  const put = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };
  const dir = (d) => fs.mkdirSync(d, { recursive: true });
  // Every layout's .specs/ also holds work/tasks.md naming `npm test` (no signal of the rule — a folder without .state.json or
  // classification.md), so the observe hook has a run to log wherever it finds the project.
  const TASKS = "# Tasks\n\n- [ ] 1. Build it\n  - _Verify: `npm test`_\n";
  const ROADMAP_MD = "<!-- AUTO-GENERATED by dev-spec — do not edit -->\n# Roadmap\n";
  const layout = (name, make, cwdRel) => {
    const root = path.join(base, name);
    dir(path.join(root, "src", "deep"));
    make(root);
    return { name, root, cwd: path.join(root, ...(cwdRel || ["src", "deep"])) };
  };
  const specs = (root, ...p) => path.join(root, ".specs", ...p);
  const L = [
    layout("none", () => {}),
    layout("empty", (r) => dir(specs(r))),
    layout("other-tool", (r) => { put(specs(r, "notes", "requirements.md"), "# R\n"); put(specs(r, "ROADMAP.md"), "# Our roadmap\n"); put(specs(r, "work", "tasks.md"), TASKS); }),
    layout("roadmap-only", (r) => { put(specs(r, "roadmap.json"), js({ features: {}, meta: {} })); put(specs(r, "work", "tasks.md"), TASKS); }),
    layout("steering-only", (r) => { put(specs(r, "steering", "product.md"), "# Product\n"); put(specs(r, "work", "tasks.md"), TASKS); }),
    layout("steering-file", (r) => { put(specs(r, "steering"), "not a folder\n"); put(specs(r, "work", "tasks.md"), TASKS); }),
    layout("classified-only", (r) => { put(specs(r, "alpha", "classification.md"), "# Classification\n"); put(specs(r, "work", "tasks.md"), TASKS); }),
    layout("state-only", (r) => { put(specs(r, "alpha", ".state.json"), js({ lang: "en", tracks: ["core"] })); put(specs(r, "work", "tasks.md"), TASKS); }),
    layout("dot-folders", (r) => {
      put(specs(r, ".removing-alpha", ".state.json"), "{}"); put(specs(r, ".old", "classification.md"), "# C\n"); put(specs(r, ".execution", "roadmap-stale"), "");
      put(specs(r, "work", "tasks.md"), TASKS);
    }),
    layout("generated-roadmap-md", (r) => { put(specs(r, "ROADMAP.md"), ROADMAP_MD); put(specs(r, "work", "tasks.md"), TASKS); }),
    // a monorepo: a package's classified feature is ITS project (the nearest); another tool's .specs/ in a package is skipped for the
    // dev-spec project above it
    layout("mono-classified", (r) => {
      put(specs(r, "roadmap.json"), js({ features: {}, meta: {} })); put(specs(r, "work", "tasks.md"), TASKS);
      put(path.join(r, "packages", "app", ".specs", "alpha", "classification.md"), "# C\n"); put(path.join(r, "packages", "app", ".specs", "work", "tasks.md"), TASKS);
      dir(path.join(r, "packages", "app", "src"));
    }, ["packages", "app", "src"]),
    layout("mono-other-tool", (r) => {
      put(specs(r, "roadmap.json"), js({ features: {}, meta: {} })); put(specs(r, "work", "tasks.md"), TASKS);
      put(path.join(r, "packages", "lib", ".specs", "notes", "x.md"), "# notes\n");
      dir(path.join(r, "packages", "lib", "src"));
    }, ["packages", "lib", "src"]),
  ];
  // The project each layout's cwd belongs to, as the rule reads it (null: none) — what every surface must answer.
  const WANT = { none: null, empty: null, "other-tool": null, "roadmap-only": "", "steering-only": "", "steering-file": null, "classified-only": "",
    "state-only": "", "dot-folders": null, "generated-roadmap-md": "", "mono-classified": "packages/app", "mono-other-tool": "" };
  const want = (l) => (WANT[l.name] === null ? null : path.join(l.root, ...WANT[l.name].split("/").filter(Boolean)));
  const same = (a, b) => (a == null || b == null ? a == b : path.resolve(a).toLowerCase() === path.resolve(b).toLowerCase()); // eslint-disable-line eqeqeq

  // (a) in process — the probe, the engine (isDevSpecDir, statusLineProject, sessionProject, the CLI resolver's walk), the status line's
  // probe and the shell completion's resolver, hook-utils' approval candidates
  const inProcess = L.map((l) => {
    const w = want(l);
    const got = {
      probe: P.nearestDevSpec(l.cwd), probeRule: w ? P.isDevSpecProject(w) : P.isDevSpecProject(l.root),
      engineRule: w ? S.isDevSpecDir(w) : S.isDevSpecDir(l.root), statusLine: S.statusLineProject([l.cwd]),
      session: (S.sessionProject({ cwd: l.cwd, anchors: [] }) || {}).project || null, statusProbe: C.statusProbe([l.cwd]),
      sessionProjects: P.sessionProjects({ cwd: l.cwd, anchors: [] })[0] || null,
    };
    const bad = [];
    for (const k of ["probe", "statusLine", "session", "sessionProjects"]) if (!same(got[k], w)) bad.push(k + "=" + got[k]);
    if (got.probeRule !== !!w || got.engineRule !== !!w) bad.push("rule " + got.probeRule + "/" + got.engineRule);
    if (got.statusProbe !== !!w) bad.push("statusProbe=" + got.statusProbe);
    return bad.length ? l.name + ": " + bad.join(", ") : null;
  }).filter(Boolean);
  // the CLI's resolver walk: start itself with any .specs/, else the nearest dev-spec one above — the engine's resolveProjectDir (in a
  // child: run from each layout's src/ with no project variable), the completion's resolveProject, hook-utils' approval candidates (a cd
  // target), all the probe's nearestProject
  const resolverScript = path.join(base, "resolver-check.js");
  fs.writeFileSync(resolverScript, [
    "const path = require('path');",
    "const [lib, cli, dirs] = JSON.parse(process.argv[2]);",
    "const S = require(path.join(lib, 'spec.js')), C = require(path.join(cli, 'completion.js'));",
    "process.stdout.write(JSON.stringify(dirs.map((d) => { process.chdir(d); return [S.resolveProjectDir(), C.resolveProject(undefined, {})]; })));",
  ].join("\n"));
  const subs = L.map((l) => path.join(l.root, "src"));
  const rr = spawnSync(process.execPath, [resolverScript, js([path.join(__dirname, "lib"), path.join(__dirname, "..", "cli"), subs])],
    { encoding: "utf8", cwd: tmp, env: { ...process.env, CLAUDE_PROJECT_DIR: "", SPEC_PROJECT_DIR: "" }, timeout: 60000 });
  let resolved = [];
  try { resolved = JSON.parse(rr.stdout); } catch { resolved = []; }
  const resolver = L.map((l, i) => {
    const pr = P.nearestProject(subs[i]);
    const r = resolved[i] || [];
    const cd = HU.approvalProjects({ cwd: l.root, command: "cd src && node cli/dev-spec.js status" });
    return same(r[0], pr || subs[i]) && same(r[1], pr || subs[i]) && (pr === null || cd.some((d) => same(d, pr))) ? null
      : l.name + ": engine " + r[0] + " completion " + r[1] + " probe " + pr + " candidates " + js(cd);
  }).filter(Boolean);
  ok(inProcess.length === 0 && resolver.length === 0,
    "1.27: on " + L.length + " layouts (none, an empty / another tool's .specs/ (a hand-written ROADMAP.md), roadmap.json only, steering/ only, a steering FILE, a classified feature only, a .state.json only, dot folders, a generated ROADMAP.md only — a v1.8-era project —, a monorepo package classified / of another tool) the probe, the engine (isDevSpecDir, statusLineProject, sessionProject, nearestProject), the status line's statusProbe, the completion and the approval candidates agree (got " +
    js({ inProcess, resolver }) + ")");

  // (b) the hooks, each in its own process, the engine-load as the observable (a preload records whether mcp/lib/spec.js was loaded): a
  // hook loads it exactly when the probe finds a project — SessionStart (its probe), SubagentStop (the stop gate on: no roadmap meta), the
  // edit guard (DEV_SPEC_GUARD_DEFAULT=on: every dev-spec project is guarded), the observe hook (`npm test` is in work/tasks.md) and the
  // plan hook. No CLAUDE_PROJECT_DIR / SPEC_PROJECT_DIR: the cwd alone decides.
  const pre = path.join(base, "preload.js");
  fs.writeFileSync(pre, "process.on('exit', () => { if (process.env.PROBE_OUT) require('fs').writeFileSync(process.env.PROBE_OUT, String(Object.keys(require.cache).some((k) => /[" +
    BS + BS + "/]mcp[" + BS + BS + "/]lib[" + BS + BS + "/]spec" + BS + ".js$/.test(k)))); });\n");
  const events = (cwd) => ({
    "spec-hook": { session_id: "s", hook_event_name: "SessionStart", source: "startup", cwd },
    "stop-hook": { session_id: "s", hook_event_name: "SubagentStop", agent_type: "dev-spec-driven:spec-implementer", stop_hook_active: false, cwd, last_assistant_message: "DONE — task 1." },
    "guard-hook": { session_id: "s", hook_event_name: "PreToolUse", tool_name: "Write", cwd, tool_input: { file_path: path.join(cwd, "a.ts"), content: "x" } },
    "observe-hook": { session_id: "s", hook_event_name: "PostToolUse", tool_name: "Bash", cwd, tool_input: { command: "npm test" }, tool_response: { stdout: "ok", exit_code: 0 } },
    "plan-hook": { session_id: "s", hook_event_name: "PostToolUse", tool_name: "ExitPlanMode", cwd, tool_input: { plan: "# Plan\n- a" } },
  });
  const env = { ...process.env, CLAUDE_PROJECT_DIR: "", SPEC_PROJECT_DIR: "", DEV_SPEC_GUARD_DEFAULT: "on" };
  const jobs = [];
  L.forEach((l, i) => Object.entries(events(l.cwd)).forEach(([h, payload]) => jobs.push({ l, h, payload, out: path.join(base, "out-" + i + "-" + h) })));
  const runOne = (j) => new Promise((resolve) => {
    const c = spawn(process.execPath, ["-r", pre, path.join(HOOKS, j.h + ".js")], { cwd: tmp, env: { ...env, PROBE_OUT: j.out }, stdio: ["pipe", "ignore", "ignore"] });
    const t = setTimeout(() => c.kill(), 30000);
    c.on("error", () => { clearTimeout(t); resolve(); });
    c.on("close", () => { clearTimeout(t); resolve(); });
    c.stdin.end(js(j.payload));
  });
  for (let k = 0; k < jobs.length; k += 6) await Promise.all(jobs.slice(k, k + 6).map(runOne)); // six at a time
  const hooks = jobs.map((j) => {
    const loaded = fs.existsSync(j.out) ? fs.readFileSync(j.out, "utf8") === "true" : "no output";
    return loaded === !!want(j.l) ? null : j.l.name + " / " + j.h + ": engine loaded " + loaded;
  }).filter(Boolean);
  ok(hooks.length === 0,
    "1.27: SessionStart, the stop gate (SubagentStop), the edit guard, the observe hook and the plan hook take a layout for a dev-spec project exactly when the probe does — " + jobs.length + " runs, the engine loaded only then (got " + js(hooks) + ")");

  // (c) `~` (the status line's --project, the CLI's resolver, a SPEC_PROJECT_DIR from a JSON config): the home folder, alike everywhere — in
  // a child whose home is a temp folder (os.homedir() reads USERPROFILE / HOME)
  {
    const home = path.join(base, "home");
    put(path.join(home, "proj", ".specs", "alpha", "classification.md"), "# C\n");
    dir(path.join(home, "proj", "src"));
    const script = path.join(base, "home-check.js");
    fs.writeFileSync(script, [
      "const path = require('path');",
      "const [lib, cli] = JSON.parse(process.argv[2]);",
      "const P = require(path.join(lib, 'probe.js')), S = require(path.join(lib, 'spec.js')), C = require(path.join(cli, 'completion.js'));",
      "process.stdout.write(JSON.stringify({ probe: P.nearestDevSpec(P.expandHome('~/proj/src')), engine: S.statusLineProject(['~/proj/src']), statusProbe: C.statusProbe(['~/proj/src']),",
      "  resolve: C.resolveProject('~/proj'), engineResolve: S.resolveProjectDir('~/proj'), expand: [P.expandHome('~'), S.expandHome('~')] }));",
    ].join("\n"));
    const r = spawnSync(process.execPath, [script, js([path.join(__dirname, "lib"), path.join(__dirname, "..", "cli")])],
      { encoding: "utf8", cwd: tmp, env: { ...process.env, HOME: home, USERPROFILE: home, CLAUDE_PROJECT_DIR: "", SPEC_PROJECT_DIR: "" }, timeout: 60000 });
    let g = null;
    try { g = JSON.parse(r.stdout); } catch { g = { stdout: r.stdout, stderr: String(r.stderr).slice(0, 300) }; }
    const proj = path.join(home, "proj");
    all("1.27: a leading ~ is the home folder for the probe, the engine's status line, statusProbe and both resolvers (a classified-only project there is found by each) (got " + js(g) + ")", {
      probe: () => same(g.probe, proj), engine: () => same(g.engine, proj), statusProbe: () => g.statusProbe === true,
      resolve: () => same(g.resolve, proj) && same(g.engineResolve, proj), expand: () => same(g.expand[0], home) && same(g.expand[1], home),
    });
  }

  // (d) network and device paths: decided on their text, never stat'ed, never walked — the probe, the engine and hook-utils read them alike;
  // \\?\C:\… and WSL's \\wsl$\ are local (on Windows, a project named through \\?\ is found by every surface)
  {
    const net = [BS + BS + "192.0.2.1" + BS + "share" + BS + "p", "//192.0.2.1/share/p", BS + BS + "?" + BS + "UNC" + BS + "192.0.2.1" + BS + "share", BS + BS + "." + BS + "pipe" + BS + "x"];
    const local = [BS + BS + "?" + BS + "C:" + BS + "x", BS + BS + "wsl$" + BS + "Ubuntu" + BS + "home", "//wsl.localhost/Ubuntu/home", "C:" + BS + "x", "/home/x"];
    const t0 = Date.now();
    const verdicts = {
      isNetwork: net.every((p) => P.isNetwork(p) && S.isNetworkPath(p) && HU.isNetwork(p)) && local.every((p) => !P.isNetwork(p) && !S.isNetworkPath(p) && !HU.isNetwork(p)),
      notWalked: net.every((p) => P.nearestProject(p) === null && P.nearestSpecs(p) === p && !C.statusProbe([p]) && S.statusLineProject([p]) === null),
    };
    const took = Date.now() - t0;
    const dev = L.find((l) => l.name === "roadmap-only");
    const unc = BS + BS + "?" + BS + path.resolve(dev.cwd);
    const viaDevice = WIN ? [P.nearestDevSpec(unc), S.statusLineProject([unc]), C.statusProbe([unc])] : null;
    all("1.27: network / device paths are read on their text by the probe, the engine and hook-utils alike — never walked, the status line skips them before any fs call (" + took + " ms); \\\\?\\C:\\… and WSL hosts are local" +
      (WIN ? " — a project named through \\\\?\\ is found by the probe, the engine's status line and statusProbe" : "") + " (got " + js({ verdicts, took, viaDevice }) + ")", {
      isNetwork: () => verdicts.isNetwork, notWalked: () => verdicts.notWalked, fast: () => took < 2000,
      device: () => !WIN || (viaDevice[0] !== null && same(viaDevice[0].replace(/^[\\/]{2}\?[\\/]/, ""), dev.root) && viaDevice[1] !== null && viaDevice[2] === true),
    });
  }

  // (e) one copy: no hook, hook-utils.js or cli/completion.js defines its own rule, walk, network test or JSON reader any more; the
  // engine's isDevSpecDir is the probe's rule and its resolver walk (files.js nearestProject) the probe's, both through the engine's
  // reads (PROBE_IO); the engine's own walks' bounds are the probe's
  {
    const srcs = ["guard-hook.js", "stop-hook.js", "observe-hook.js", "spec-hook.js", "plan-hook.js", "approval-hook.js", "hook-utils.js"].map((f) => [f, fs.readFileSync(path.join(HOOKS, f), "utf8")])
      .concat([["cli/completion.js", fs.readFileSync(path.join(__dirname, "..", "cli", "completion.js"), "utf8")]]);
    const RE_COPY = /function (?:isDevSpecProject|isDevSpecDir|devSpecDir|nearestDevSpec|nearestSpecs|nearestProject|readJsonFile|isNetwork(?:Path)?|expandHome|utf16OrUtf8)\b|AUTO-GE\(\?:/;
    const copies = srcs.filter(([, s]) => RE_COPY.test(s)).map(([f, s]) => f + ": " + RE_COPY.exec(s)[0]);
    const eng = (f) => fs.readFileSync(path.join(__dirname, "lib", "engine", f), "utf8");
    const num = (f, name) => Number((new RegExp("const " + name + " = (\\d+);").exec(eng(f)) || [])[1]);
    const bounds = { session: num("guards.js", "SESSION_MAX_UP"), status: num("doctor.js", "STATUS_MAX_UP") };
    all("1.27: the rule lives in mcp/lib/probe.js alone — no hook, hook-utils.js or cli/completion.js keeps a copy (got " + js(copies) + "); doctor.js isDevSpecDir is the probe's rule, files.js nearestProject the probe's walk; the walks' bounds are the engine's (" + js(bounds) + ")", {
      noCopies: () => copies.length === 0,
      engineDelegates: () => /function isDevSpecDir\(dir\) \{\s*return PROBE\.isDevSpecProject\(dir, PROBE_IO\);/.test(eng("doctor.js")),
      resolverDelegates: () => /function nearestProject\(start\) \{\s*return PROBE\.nearestProject\(start, \{ io: PROBE_IO \}\);/.test(eng("files.js")) &&
        !/PROJECT_MAX_UP/.test(eng("files.js").replace(/\/\/[^\n]*/g, "")),
      // the hooks' session walk (guards.js sessionProject / worktreeProject) asks isDevSpecDir itself — its own sessionSpecs rule is gone
      sessionDelegates: () => !/function sessionSpecs\b/.test(eng("guards.js")) && /isDevSpecDir\(d\)/.test(eng("guards.js")),
      bounds: () => P.SESSION_MAX_UP === bounds.session && P.SESSION_MAX_UP === bounds.status,
      autogen: () => (/const RE_AUTOGEN = (\/.+\/);/.exec(eng("state.js")) || [])[1] === String(P.RE_AUTOGEN),
      unexpanded: () => ["${X}", "$HOME/x", "%APPDATA%", "a/${B}/c", "plain", "~/x"].every((v) => P.unexpandedVar(v) === S.unexpandedVar(v) && HU.unexpandedVar(v) === S.unexpandedVar(v)),
    });
  }
};

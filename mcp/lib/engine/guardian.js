const GUARDIAN_CHECK = "guardian";
const GUARDIAN_LAUNCHER_FILE = "guardian.cjs"; // .specs/guardian.cjs — committed with the project, like roadmap.json
const GUARDIAN_COMMAND = "node .specs/" + GUARDIAN_LAUNCHER_FILE + " scan --project . --fail-on high --format json";
const GUARDIAN_MARK = "dev-guardian launcher - generated by dev-spec-driven";
const GUARDIAN_MIN_VERSION = "3.2.1"; // the first dev-guardian whose CLI runs from a plugin install (3.2.0's: "Cannot find package")
// dev-guardian's subcommands the launcher forwards: the gate (scan), the user's remedy line (`baseline update`, run on the base
// commit) and the read-only `status` — plus its help. Anything else (db adopt, ci-init, dashboard, import-sarif…): run dev-guardian
// itself; the launcher is no general trampoline (review 8: it imported any DEV_GUARDIAN_CLI with any arguments).
const GUARDIAN_FORWARDED = ["scan", "baseline", "status"];
// The dev-guardian CLI to run — ONE rule: the engine runs this function (the offer) and the launcher carries its source
// (Function.prototype.toString, below), so the two never drift. DEV_GUARDIAN_CLI first — a file named dev-guardian.mjs, nothing
// else —; else Claude Code's plugins under CLAUDE_CONFIG_DIR (else ~/.claude): the installPath plugins/installed_plugins.json
// records for dev-guardian@<marketplace> (an install scoped to this project — its projectPath — over the user's; then the newest
// version) whose cli/dev-guardian.mjs is a file. That file decides when it reads: a dev-guardian it doesn't list is not installed
// (a cache folder left behind, a disabled copy elsewhere, is no install). Without it (a copied cache, an older Claude Code), the
// newest x.y.z folder (semver only — a commit-hash folder is no version) of plugins/cache/<marketplace>/dev-guardian/ holding the
// CLI and not marked .orphaned_at. → { cli, override? } | { error }. Node core only, handed in; no backslash, no backtick and
// no template placeholder in it (it is carried as text), CRLF-safe (the text is normalized).
function findDevGuardian(env, cwd, fs, path, os) {
  const ENTRY = "dev-guardian.mjs";
  const isFile = (f) => { try { return fs.statSync(f).isFile(); } catch (e) { return false; } };
  const list = (d) => { try { return fs.readdirSync(d); } catch (e) { return []; } };
  const semver = (v) => (/^[0-9]{1,6}[.][0-9]{1,6}[.][0-9]{1,6}$/.test(String(v)) ? String(v).split(".").map(Number) : null);
  const newer = (a, b) => {
    const x = semver(a) || [-1, 0, 0], y = semver(b) || [-1, 0, 0];
    for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] > y[i];
    return false;
  };
  // (the paths are the user's own config folder, the file Claude Code writes there and the folder names under it)
  // nosemgrep: javascript.lang.security.audit.path-traversal.path-join-resolve-traversal.path-join-resolve-traversal
  const join = (...parts) => path.join(...parts);
  // nosemgrep: javascript.lang.security.audit.path-traversal.path-join-resolve-traversal.path-join-resolve-traversal
  const same = (a, b) => { const x = path.resolve(a), y = path.resolve(b); return process.platform === "win32" ? x.toLowerCase() === y.toLowerCase() : x === y; };
  const own = String(env.DEV_GUARDIAN_CLI || "").trim();
  if (own) {
    if (path.basename(own) !== ENTRY) return { error: "DEV_GUARDIAN_CLI must name a file called " + ENTRY + " (got " + own + ")" };
    return isFile(own) ? { cli: own, override: true } : { error: "DEV_GUARDIAN_CLI names no file (" + own + ")" };
  }
  const home = String(env.CLAUDE_CONFIG_DIR || "").trim() || join(os.homedir(), ".claude");
  const installed = join(home, "plugins", "installed_plugins.json");
  let j = null;
  try { j = JSON.parse(fs.readFileSync(installed, "utf8")); } catch (e) { j = null; }
  if (j && typeof j === "object" && !Array.isArray(j)) {
    const plugins = j.plugins && typeof j.plugins === "object" ? j.plugins : {};
    let pick = null;
    for (const key of Object.keys(plugins)) {
      if (key.indexOf("dev-guardian@") !== 0 || !Array.isArray(plugins[key])) continue;
      for (const e of plugins[key]) {
        if (!e || typeof e.installPath !== "string" || !e.installPath) continue;
        const scoped = typeof e.projectPath === "string" && e.projectPath !== "";
        if (scoped && !same(e.projectPath, cwd)) continue; // another project's install
        const cli = join(e.installPath, "cli", ENTRY);
        const rank = scoped ? 1 : 0;
        if (isFile(cli) && (!pick || rank > pick.rank || (rank === pick.rank && newer(e.version, pick.version)))) pick = { rank, version: e.version, cli };
      }
    }
    return pick ? { cli: pick.cli } : { error: "no dev-guardian in " + installed + " — install it, or set DEV_GUARDIAN_CLI to the path of its cli/" + ENTRY };
  }
  const cache = join(home, "plugins", "cache");
  let best = null;
  for (const market of list(cache)) {
    const base = join(cache, market, "dev-guardian");
    for (const version of list(base)) {
      const cli = join(base, version, "cli", ENTRY);
      if (semver(version) && !fs.existsSync(join(base, version, ".orphaned_at")) && isFile(cli) && (!best || newer(version, best.version))) best = { version, cli };
    }
  }
  return best ? { cli: best.cli } : { error: "no dev-guardian plugin in " + cache + " — install it, or set DEV_GUARDIAN_CLI to the path of its cli/" + ENTRY };
}
// The launcher's source (Node core only, no backslash). It never calls process.exit (a message to a pipe would be cut): exitCode 3
// when nothing is found, the subcommand is not forwarded or the CLI does not load, else dev-guardian's own exit. A DEV_GUARDIAN_CLI
// it ran is said on stderr ("dev-guardian launcher: DEV_GUARDIAN_CLI=<path>") — the verdict and the merge summary name it.
const GUARDIAN_LAUNCHER = `#!/usr/bin/env node
// ${GUARDIAN_MARK} (dev-spec init --guardian). Do not edit it:
// the gate runs it only while it is the file dev-spec-driven writes — init --guardian (or upgrade --apply) writes it again.
//
// The project check "guardian" (.specs/roadmap.json meta.checks) runs, from the project root:
//   ${GUARDIAN_COMMAND}
// This file finds the installed dev-guardian at each run (findDevGuardian, below) and hands its CLI the arguments after its own
// name, so the check keeps working after an update of either plugin. It forwards ${GUARDIAN_FORWARDED.join(", ")} and help — the
// gate and its remedies; run any other subcommand with dev-guardian itself. Nothing found, another subcommand, or a CLI that does
// not load: exit 3 — dev-guardian's own code for a usage or configuration error.
"use strict";
${findDevGuardian.toString().replace(/\r\n/g, "\n")}

const FORWARDED = ${JSON.stringify(GUARDIAN_FORWARDED.concat(["help", "--help", "-h"]))};
const sub = process.argv[2];
if (!FORWARDED.includes(sub)) {
  console.error("dev-guardian launcher: " + (sub ? "'" + sub + "' is not forwarded" : "no subcommand") + " — only " + FORWARDED.slice(0, ${GUARDIAN_FORWARDED.length}).join(", ") + " and help; run other subcommands with dev-guardian itself");
  process.exitCode = 3;
} else {
  const found = findDevGuardian(process.env, process.cwd(), require("fs"), require("path"), require("os"));
  if (found.error) {
    console.error("dev-guardian not found: " + found.error);
    process.exitCode = 3;
  } else {
    if (found.override) console.error("dev-guardian launcher: DEV_GUARDIAN_CLI=" + found.cli);
    // dev-guardian runs as the entry point (it compares argv[1] with its own path) and reads its arguments from argv[2] on
    process.argv[1] = found.cli;
    import("node:url").then((u) => import(u.pathToFileURL(found.cli).href)).catch((e) => {
      console.error("dev-guardian could not be loaded from " + found.cli + ": " + (e && e.message ? e.message : e));
      process.exitCode = 3;
    });
  }
}
`;
// The launchers earlier versions wrote (sha1 of the LF text): genuine, only older — finish --run writes this version's in their
// place before it runs the check, spec_upgrade --apply too. 1.29.x: the newest version by numeric parts, any DEV_GUARDIAN_CLI file,
// every subcommand.
const GUARDIAN_LAUNCHER_PAST = ["7698ebe162c94bc3e55dd8357fd53c5947a89764"];
const GUARDIAN_LAUNCHER_MAX = 256 * 1024; // a larger file is no launcher of ours (never read whole)
// Does a project check run dev-guardian's gate? The check named "guardian", or a command naming dev-guardian (or the launcher)
// followed by `scan`.
const RE_GUARDIAN_SCAN = /(?:^|[\s"'/\\])(?:dev-guardian(?:\.mjs)?|guardian\.cjs)["']?\s+scan(?=\s|$)/i;
const isGuardianCheck = (name, command) => name === GUARDIAN_CHECK || RE_GUARDIAN_SCAN.test(String(command || ""));
// a command that runs the project's launcher (.specs/guardian.cjs) — the file verified before a run and when one is recorded
const RE_LAUNCHER_RUN = /(?:^|[\s"'/\\])\.specs[\\/]+guardian\.cjs["']?(?=\s|$)/i;
// spec_init {checks} + {guardian}: true / false adds / removes the `guardian` check on top of the checks given (a checks value that
// is no object stays as it is — checksInput refuses it). The approval guard reads the same map (guards.js initGuardDowns).
function guardianChecks(checks, on) {
  if ((on !== true && on !== false) || (checks != null && !isObj(checks))) return checks;
  return { ...(checks || {}), [GUARDIAN_CHECK]: on ? GUARDIAN_COMMAND : "" };
}
const launcherPath = (projectDir) => path.join(specsRoot(projectDir), GUARDIAN_LAUNCHER_FILE);
// The launcher on (written when absent or different — a CRLF checkout of it is the same file) or off (removed only when it is the
// generated one). → "written" | "removed" | null (nothing changed). A path the write gate refuses (a folder, a link) throws.
function setGuardianLauncher(projectDir, on) {
  const file = launcherPath(projectDir);
  const cur = readIfExists(file);
  if (on) {
    if (cur != null && cur.replace(/\r\n/g, "\n") === GUARDIAN_LAUNCHER) return null;
    writeFileAtomic(file, GUARDIAN_LAUNCHER);
    return "written";
  }
  return cur != null && cur.includes(GUARDIAN_MARK) && removeSpecFile(file) ? "removed" : null;
}
// init --guardian on: the launcher is written BEFORE meta.checks names the check (review 8: a folder at .specs/guardian.cjs failed
// the write after the check was stored — a check that could never run). → { refusal } (the write gate's, in lng) | { wrote } (it
// was not there: removed again when meta.checks can't be written — initProject) | {}.
function guardianLauncherOn(projectDir, lng) {
  const existed = readIfExists(launcherPath(projectDir)) != null;
  try {
    const r = setGuardianLauncher(projectDir, true);
    return r === "written" && !existed ? { wrote: true } : {};
  } catch (e) {
    const refusal = gateRefusal(e, lng);
    if (refusal) return { refusal };
    throw e;
  }
}
// What .specs/guardian.cjs is: "ok" (this version's launcher, CRLF read as LF) · "outdated" (an earlier version's, byte for byte —
// GUARDIAN_LAUNCHER_PAST) · "missing" · "changed" (anything else: edited, replaced, a link, a folder, too large). Read raw, never
// through a link.
function guardianLauncherState(projectDir) {
  const file = launcherPath(projectDir);
  let st;
  try { st = fs.lstatSync(file); } catch { return "missing"; }
  if (!st.isFile() || st.size > GUARDIAN_LAUNCHER_MAX) return "changed";
  let text;
  try { text = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n"); } catch { return "changed"; }
  if (text === GUARDIAN_LAUNCHER) return "ok";
  return GUARDIAN_LAUNCHER_PAST.includes(sha1Hex(text)) ? "outdated" : "changed";
}
// finish --run, before it runs anything (review 8: the gate ran whatever .specs/guardian.cjs held — a stub printing exit 0 passed
// it, recorded as the CLI's own run): a guardian check that runs the launcher needs it to be this version's. An earlier version's is
// replaced first (note); a missing one (no-launcher) or any other file (launcher-changed) refuses the run — nothing runs, nothing is
// recorded. → { ok: true, note? } | { ok: false, code, error }
function guardianPreRun(projectDir, checks, lng) {
  const G = i18n.msg(lng).guardian;
  const mine = (checks || []).filter((c) => isGuardianCheck(c.name, c.command) && RE_LAUNCHER_RUN.test(c.command));
  if (!mine.length) return { ok: true };
  const s = guardianLauncherState(projectDir);
  if (s === "ok") return { ok: true };
  if (s === "outdated") {
    try {
      setGuardianLauncher(projectDir, true);
      return { ok: true, note: G.launcherRefreshed };
    } catch (e) {
      const refusal = gateRefusal(e, lng);
      if (refusal) return { ok: false, code: "launcher-changed", error: G.notRun(mine[0].name, refusal.error) };
      throw e;
    }
  }
  return { ok: false, code: s === "missing" ? "no-launcher" : "launcher-changed", error: G.notRun(mine[0].name, s === "missing" ? G.noLauncher : G.launcherChanged) };
}
// spec_upgrade: a guardian check runs the launcher and it is not this version's → the localized attention line | null;
// apply → writes it (fix: true) → "written" | null.
function guardianLauncherAudit(projectDir, lng, fix) {
  if (!projectChecks(projectDir).checks.some((c) => isGuardianCheck(c.name, c.command) && RE_LAUNCHER_RUN.test(c.command))) return null;
  const s = guardianLauncherState(projectDir);
  if (s === "ok") return null;
  if (!fix) return i18n.msg(lng).guardian.upgradeLauncher(s);
  try { return setGuardianLauncher(projectDir, true); } catch (e) { if (gateRefusal(e, lng)) return null; throw e; }
}
// The dev-guardian CLI the launcher would run (findDevGuardian, the same function) — what init / spec_upgrade offer the gate
// from: folder listings and installed_plugins.json, outside the project (the one engine read of the user's config folder).
// env: the environment (default the process's); cwd: the project (an install scoped to it). → its path | null
function guardianCli(env, cwd) {
  const r = findDevGuardian(env || process.env, cwd || process.cwd(), fs, path, os);
  return r.cli || null;
}
// init / spec_upgrade OFFER the gate, never enable it (its scan takes minutes and needs dev-guardian's scanners): dev-guardian is
// installed (guardianCli) or the project holds a .guardian/ folder, and no project check runs it. → the localized line | null
function guardianOffer(projectDir, lng) {
  if (projectChecks(projectDir).checks.some((c) => isGuardianCheck(c.name, c.command))) return null;
  const installed = !!guardianCli(null, path.resolve(projectDir)), project = isDirSafe(path.join(path.resolve(projectDir), ".guardian"));
  return installed || project ? i18n.msg(lng).guardian.offer(installed, project) : null;
}
// The lines dev-guardian's own .gitignore block writes (gitignoreGuard: its outputs ignored, the files a team shares kept) — dev-spec
// never writes outside .specs/, so `init --guardian` names the ones the project's .gitignore lacks.
const GUARDIAN_IGNORE = ["**/.guardian/*", "!**/.guardian/baseline.json", "!**/.guardian/budgets.yml", "!**/.guardian/hooks.config.json"];
const RE_GUARDIAN_IGNORED = /^\/?(?:\*\*\/)?\.guardian\/?\*?$/; // the ignore line in any spelling dev-guardian wrote
function guardianIgnoreMissing(projectDir) {
  const text = readIfExists(path.join(path.resolve(projectDir), ".gitignore")) || "";
  const lines = new Set(text.split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith("#")));
  const has = (l) => lines.has(l) || lines.has(l.replace("**/", "")) || (l === GUARDIAN_IGNORE[0] && [...lines].some((x) => RE_GUARDIAN_IGNORED.test(x)));
  return GUARDIAN_IGNORE.filter((l) => !has(l));
}
// init --guardian on → its note: the gate is set (project-wide, its scanners on every machine) + no baseline yet (record one now,
// the user's step) + the .gitignore lines the project lacks.
function guardianOnNote(projectDir, command, lng) {
  const G = i18n.msg(lng).guardian;
  const root = path.resolve(projectDir);
  const parts = [G.on(command)];
  if (readIfExists(path.join(root, ".guardian", "baseline.json")) == null) parts.push(G.initBaseline);
  const missing = guardianIgnoreMissing(projectDir);
  if (missing.length) parts.push(G.initIgnore(missing));
  return parts.join(" ");
}

const GUARDIAN_TOP = 5; // the blocking findings a summary keeps — the feature's own first
const GUARDIAN_REPORT_MAX = 16 * 1024 * 1024; // a larger report is not parsed: the exit code alone
const GUARDIAN_JSON_STARTS = 8; // lines starting with "{" tried as the report's start, at most (text around the JSON)
const GUARDIAN_GAP_KINDS = ["missing_tool", "no_lockfile", "partial_parse", "file_timeout", "taint_timeout", "path_too_long", "scanner_failed", "skipped", "other"];
const SEVERITY_RANK = { critical: 4, high: 3, medium: 2, low: 1, info: 0 };
// report-derived text as one inert line: line breaks folded (oneLine), every other control character a space, at most max characters
// (review 8: a finding's file_path holding "\n## Approved…" wrote lines into the merge summary and the blocker).
// (the class built from character codes: an editor turns the escapes of U+2028 / U+2029 into the characters, which end a regex literal)
const RE_REPORT_CONTROL = new RegExp("[" + String.fromCharCode(0) + "-" + String.fromCharCode(0x1f) + String.fromCharCode(0x7f) + "-" +
  String.fromCharCode(0x9f) + String.fromCharCode(0x2028, 0x2029) + "]+", "g");
const cleanLine = (v, max) => oneLine(String(v == null ? "" : v)).replace(RE_REPORT_CONTROL, " ").trim().slice(0, max);
const gateShape = (j) => isRecord(j) && (Array.isArray(j.blocking_findings) || Array.isArray(j.new_findings) || Number.isInteger(j.exit_code));
// From s[i] (a "{"), the index of the "}" that closes it — strings (with their escapes) skipped — or -1. Linear in the span read.
function balancedEnd(s, i) {
  let depth = 0;
  for (let k = i; k < s.length; k++) {
    const c = s.charCodeAt(k);
    if (c === 34) { // a string: to its closing quote, past every escaped character
      for (k++; k < s.length && s.charCodeAt(k) !== 34; k++) if (s.charCodeAt(k) === 92) k++;
    } else if (c === 123) depth++;
    else if (c === 125 && --depth === 0) return k;
  }
  return -1;
}
// dev-guardian's `scan --format json` report (its stdout) → the object, or null. A BOM, whitespace and lines around it (a warning
// before, a note after — braces in them too: review 8 lost the report behind "[info] scanning {semgrep, gitleaks}") are tolerated:
// the whole text first, else each line starting with "{" (at most GUARDIAN_JSON_STARTS) read to its balanced end — the first that
// parses as the gate's verdict (exit_code, new_findings or blocking_findings). Bounded: GUARDIAN_REPORT_MAX characters.
function guardianJson(text) {
  if (typeof text !== "string" || !text.trim() || text.length > GUARDIAN_REPORT_MAX) return null;
  const t = text.split(BOM_CHAR).join("");
  const parse = (s) => { try { const j = JSON.parse(s); return gateShape(j) ? j : null; } catch { return null; } };
  const whole = parse(t.trim());
  if (whole) return whole;
  let starts = 0;
  for (let i = 0; i < t.length && starts < GUARDIAN_JSON_STARTS; ) {
    if (t.charCodeAt(i) === 123) {
      starts++;
      const end = balancedEnd(t, i);
      if (end > i) {
        const j = parse(t.slice(i, end + 1));
        if (j) return j;
      }
    }
    const nl = t.indexOf("\n", i);
    if (nl < 0) break;
    i = nl + 1;
  }
  return null;
}
// The lines of dev-guardian's own message (a usage or configuration error goes to stderr: "error: …", "dev-guardian: …" — never the
// launcher's DEV_GUARDIAN_CLI line), else the output's last two lines — one line, at most 300 characters.
function guardianMessage(text) {
  const lines = String(text || "").split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !RE_LAUNCHER_OVERRIDE.test(l));
  const own = lines.filter((l) => /^(?:error:|dev-guardian\b)/i.test(l));
  return cleanLine((own.length ? own : lines.slice(-2)).join(" · "), 300);
}
const RE_LAUNCHER_OVERRIDE = /^dev-guardian launcher: DEV_GUARDIAN_CLI=(.+)$/m;
// "3.2.0" below "3.2.1"? (x.y.z — a suffix like -beta read as its x.y.z; unreadable → below: dev-spec can't tell, so it says so)
function versionBelow(v, min) {
  const m = /^v?(\d{1,6})\.(\d{1,6})\.(\d{1,6})/.exec(String(v || "").trim());
  if (!m) return true;
  const want = min.split(".").map(Number);
  for (let i = 0; i < 3; i++) if (Number(m[i + 1]) !== want[i]) return Number(m[i + 1]) < want[i];
  return false;
}
// A guardian check's run → its summary (finishChecks[name].guardian, suiteChecks[].guardian): { verdict — stable: pass · blocked ·
// incomplete · config · not-found (the launcher found no dev-guardian) · no-launcher (.specs/guardian.cjs is missing) · exit (any
// other code) —, exit, failOn (the command's --fail-on, else high), parsed (the JSON report was read), blocking?, newFindings? (the
// report's new_findings_count — --compact —, else its new_findings), own? (blocking findings in the feature's _Implements:_ files),
// top? (≤ GUARDIAN_TOP: {severity, rule, file, line, own} — own first, then by severity, then the report's order), gaps? (coverage
// gaps, ≤ 3), gapDetails? (the gating coverage_gap_details, ≤ 5: {tool, kind, remedy?}), message? (config: dev-guardian's own),
// baseline? ("absent": every existing finding counted as new), tool? (the report's tool_version), update? (dev-guardian is older
// than GUARDIAN_MIN_VERSION, reported no version, or could not load a package), override? (the DEV_GUARDIAN_CLI the launcher ran) }
// — and what recordFinishChecks refuses on (never stored): launcher ("changed" | "missing" — the launcher as the run is recorded),
// mismatch (the report contradicts the exit code: reportExit = its exit_code), noReport (exit 0 with no readable report).
// report: the JSON on stdout; output: the rest (stderr — over MCP the evidence's summary). dir: the feature folder (own), or null.
function guardianRecord(projectDir, dir, command, exitCode, report, output) {
  const code = Number.isInteger(exitCode) ? exitCode : parseInt(exitCode, 10);
  const cmd = String(command || "");
  const fo = /--fail-on[=\s]+(info|low|medium|high|critical)\b/i.exec(cmd);
  const text = String(output || "");
  const j = guardianJson(report);
  const g = { verdict: "exit", exit: Number.isInteger(code) ? code : null, failOn: fo ? fo[1].toLowerCase() : "high", parsed: !!j };
  // the launcher as the engine sees it now: a missing one is its own verdict whatever the output kept (review 8: the summary's last
  // lines had lost node's "Cannot find module" — recorded "blocked", with how to fix findings)
  const launcher = RE_LAUNCHER_RUN.test(cmd) ? guardianLauncherState(projectDir) : null;
  if (launcher === "missing" && code !== 0) g.verdict = "no-launcher";
  else if (code === 0) g.verdict = "pass";
  else if (code === 1) g.verdict = !j && /Cannot find module[^\n]*guardian\.cjs/.test(text) ? "no-launcher" : "blocked";
  else if (code === 2) g.verdict = "incomplete";
  else if (code === 3) g.verdict = /dev-guardian not found/.test(text) ? "not-found" : "config";
  if (launcher === "changed" || launcher === "missing") g.launcher = launcher;
  if (g.verdict === "config") g.message = guardianMessage(text);
  if (/Cannot find package/.test(text)) g.update = true; // dev-guardian ≤ 3.2.0's CLI, run from a plugin install
  const ov = RE_LAUNCHER_OVERRIDE.exec(text);
  if (ov) g.override = cleanLine(ov[1], 300);
  if (!j) {
    if (code === 0 && /--format[=\s]+json\b/i.test(cmd) && RE_GUARDIAN_SCAN.test(cmd)) g.noReport = true;
    return g;
  }
  const tool = typeof j.tool_version === "string" && j.tool_version.trim() ? cleanLine(j.tool_version, 32) : null;
  if (tool) g.tool = tool;
  if (!tool || versionBelow(tool, GUARDIAN_MIN_VERSION)) g.update = true;
  if (j.baseline_absent === true || j.baseline_status === "absent") g.baseline = "absent";
  const list = (k) => (Array.isArray(j[k]) ? j[k].filter(isRecord) : null);
  const blocking = list("blocking_findings"), fresh = list("new_findings");
  if (Number.isSafeInteger(j.new_findings_count) && j.new_findings_count >= 0) g.newFindings = j.new_findings_count;
  else if (fresh) g.newFindings = fresh.length;
  // the report contradicts the exit code (review 8: {exitCode: 0} with a report saying exit 1 and a critical finding passed)
  if (Number.isInteger(code) && ((Number.isInteger(j.exit_code) && j.exit_code !== code) || (code === 0 && blocking && blocking.length))) {
    g.mismatch = true;
    if (Number.isInteger(j.exit_code)) g.reportExit = j.exit_code;
  }
  if (Array.isArray(j.coverage_gaps)) {
    const gaps = j.coverage_gaps.filter((x) => typeof x === "string" && x.trim()).slice(0, 3).map((x) => cleanLine(x, 200));
    if (gaps.length) g.gaps = gaps;
  }
  if (Array.isArray(j.coverage_gap_details)) {
    const det = j.coverage_gap_details.filter((d) => isRecord(d) && d.gating !== false).slice(0, 5).map((d) => {
      const remedy = typeof d.remedy === "string" ? cleanLine(d.remedy, 200) : "";
      return { tool: cleanLine(d.tool, 40) || "?", kind: GUARDIAN_GAP_KINDS.includes(d.kind) ? d.kind : "other", ...(remedy ? { remedy } : {}) };
    });
    if (det.length) g.gapDetails = det;
  }
  if (!blocking) return g;
  g.blocking = blocking.length;
  const root = path.resolve(projectDir);
  const fold = FOLD_CASE ? (s) => s.toLowerCase() : (s) => s;
  const tasksText = dir ? activeTasks(readIfExists(path.join(dir, "tasks.md")) || "", detectTracks(dir)) || "" : "";
  const mine = new Set(tasksText ? baselineFiles(root, tasksText).files.map(fold) : []);
  const rel = (f) => { // a finding's file, project-relative with forward slashes, one inert line
    let p = f.replace(/\\/g, "/").replace(/^\.\//, "");
    if (path.isAbsolute(p)) { const r = path.relative(root, p); if (r && !r.startsWith("..") && !path.isAbsolute(r)) p = toPosix(r); }
    return cleanLine(p, 300);
  };
  const rank = (s) => (Object.prototype.hasOwnProperty.call(SEVERITY_RANK, s) ? SEVERITY_RANK[s] : -1);
  const items = blocking.map((f) => {
    const file = typeof f.file_path === "string" && f.file_path.trim() ? rel(f.file_path.trim()) || null : null;
    return { severity: typeof f.severity === "string" ? cleanLine(f.severity.toLowerCase(), 20) || "?" : "?", rule: cleanLine(f.rule_id || f.title || f.tool || "?", 160) || "?",
      file, line: Number.isSafeInteger(f.line_start) && f.line_start > 0 ? f.line_start : null, own: !!file && mine.has(fold(file)) };
  });
  items.sort((a, b) => (b.own ? 1 : 0) - (a.own ? 1 : 0) || rank(b.severity) - rank(a.severity)); // stable: the report's order next
  g.own = items.filter((x) => x.own).length;
  if (items.length) g.top = items.slice(0, GUARDIAN_TOP);
  return g;
}
// recordFinishChecks: a guardian run it must not record → { code, why } | null. A run of a launcher that is not this version's or
// an earlier one's (launcher-changed — the gate never vouches for a file it did not write); a pass while the launcher is missing
// (no-launcher — nothing could have run it); a report that contradicts the exit code (report-mismatch); a pass with no readable
// report (report-missing — a --format json scan always prints one).
function guardianRefusal(g, lng) {
  if (!isRecord(g)) return null;
  const G = i18n.msg(lng).guardian;
  if (g.launcher === "changed") return { code: "launcher-changed", why: G.launcherChanged };
  if (g.launcher === "missing" && g.exit === 0) return { code: "no-launcher", why: G.noLauncher };
  if (g.mismatch) return { code: "report-mismatch", why: G.reportMismatch(g.exit, g.reportExit == null ? null : g.reportExit, g.blocking || 0) };
  if (g.noReport) return { code: "report-missing", why: G.reportMissing };
  return null;
}
// What a stored summary keeps (finishChecks[name].guardian): the verdict and its facts — never the refusal flags.
function guardianStored(g) {
  const { launcher, mismatch, reportExit, noReport, ...kept } = g;
  return kept;
}
// The run's command proves a guardian check's command — or that command with --compact (dev-guardian 3.3+: the short report an
// agent can pass over MCP; the same scan and verdict). → the command to prove: `command`, or its --compact twin when the run is it.
function guardianCompact(name, command) {
  const c = String(command || "");
  return isGuardianCheck(name, c) && /--format[=\s]+json\b/i.test(c) && !/--compact\b/.test(c) ? c + " --compact" : null;
}
// A guardian summary → its localized head line (the verdict, + no baseline, + a DEV_GUARDIAN_CLI the launcher ran).
function guardianHead(g, lng) {
  const G = i18n.msg(lng).guardian;
  let head;
  switch (g.verdict) {
    case "pass": head = G.pass(g.failOn, g.newFindings || 0); break;
    case "blocked": head = G.blocked(g.blocking == null ? null : g.blocking, g.failOn, g.own || 0); break;
    case "incomplete": head = G.incomplete((g.gaps || []).join("; ")); break;
    case "config": head = G.config(g.message || ""); break;
    case "not-found": head = G.notFound; break;
    case "no-launcher": head = G.noLauncher; break;
    default: head = G.exited(g.exit);
  }
  return head + (g.baseline === "absent" ? G.noBaseline : "") + (g.override ? G.override(g.override) : "");
}
const guardianAt = (f) => (f.file ? f.file + (f.line ? ":" + f.line : "") : "?");
// finish --run's lines: the head, one per finding kept, the rest counted, then — when dev-guardian should be updated — a line saying so.
function guardianLines(g, lng) {
  const G = i18n.msg(lng).guardian;
  const top = Array.isArray(g.top) ? g.top : [];
  const out = [guardianHead(g, lng), ...top.map((f) => "  " + G.finding(guardianAt(f), f.rule, f.severity, f.own))];
  if (g.blocking > top.length && top.length) out.push("  " + G.more(g.blocking - top.length));
  if (g.update) out.push(G.update(g.tool || null));
  return out;
}
// One line — a blocker's or a status's label: the verdict, then up to 3 findings (+ update dev-guardian).
function guardianText(g, lng) {
  const G = i18n.msg(lng).guardian;
  const top = (Array.isArray(g.top) ? g.top : []).slice(0, 3);
  const rest = (g.blocking || 0) - top.length;
  return guardianHead(g, lng) + (top.length ? " — " + top.map((f) => G.finding(guardianAt(f), f.rule, f.severity, f.own)).join(", ") + (rest > 0 ? ", " + G.more(rest) : "") : "") +
    (g.update ? " · " + G.update(g.tool || null) : "");
}
// An incomplete scan → what to do, by the gating gaps' kinds (dev-guardian 3.3's coverage_gap_details): install only for a missing
// tool, a lockfile for no_lockfile, … — dev-guardian's own remedy for the others, the generic hint without details (≤ 3.2.1).
function incompleteHint(g, G) {
  const det = Array.isArray(g.gapDetails) ? g.gapDetails : [];
  if (!det.length) return G.incompleteHint;
  const H = G.gap;
  const tools = (kinds) => [...new Set(det.filter((d) => kinds.includes(d.kind)).map((d) => d.tool))].join(", ");
  const out = [];
  if (tools(["missing_tool"])) out.push(H.missingTool(tools(["missing_tool"])));
  if (tools(["no_lockfile"])) out.push(H.noLockfile(tools(["no_lockfile"])));
  if (tools(["partial_parse"])) out.push(H.partialParse(tools(["partial_parse"])));
  if (tools(["file_timeout", "taint_timeout"])) out.push(H.timeout(tools(["file_timeout", "taint_timeout"])));
  if (tools(["path_too_long"])) out.push(H.pathTooLong);
  for (const d of det.filter((x) => ["scanner_failed", "skipped", "other"].includes(x.kind))) out.push(d.remedy ? H.remedy(d.tool, d.remedy) : H.other(d.tool));
  return [...new Set(out)].join(" ") + " " + H.tail;
}
// What to do about the guardian checks among a feature's checks still missing a pass (suiteStatus().missing): a failed one with
// a summary → how to clear it (fix it, or the user suppresses one reviewed finding inline — never `baseline update`, never a forced
// finish); one that needs a run → how to run it (Claude Code: finish --run) or report it over MCP (the server runs nothing).
// → "" | " " + the sentences
function suiteGuardianHint(items, slug, lng) {
  const G = i18n.msg(lng).guardian;
  const out = [];
  for (const i of items || []) {
    if (!isGuardianCheck(i.name, i.command)) continue;
    const g = i.status === "failed" && isRecord(i.guardian) ? i.guardian : null;
    const v = g ? g.verdict : null;
    if (v === "blocked") out.push(G.fixHint(slug) + (g.baseline === "absent" ? " " + G.baselineHint : ""));
    else if (v === "incomplete") out.push(incompleteHint(g, G));
    else if (v && v !== "pass") out.push(g.update ? G.updateHint(slug) : G.configHint(slug));
    else out.push(G.mcpRun(i.name, i.command, slug));
  }
  return out.length ? " " + out.join(" ") : "";
}
// spec_finish's suite-evidence blocker: the checks without a passing run (+ how to run and report a guardian one), and apart, a
// failed dev-guardian gate with its verdict and how to clear it — never "run them" again for a scan that ran and said no.
function suiteBlocker(missing, slug, lng) {
  const failed = (missing || []).filter((i) => i.status === "failed" && isRecord(i.guardian) && isGuardianCheck(i.name, i.command));
  const rest = (missing || []).filter((i) => !failed.includes(i));
  const parts = rest.length ? [i18n.msg(lng).projectChecks.blocker(suiteLabel(rest, lng), slug) + suiteGuardianHint(rest, slug, lng)] : [];
  for (const i of failed) parts.push(i18n.msg(lng).guardian.blocker(i.name, guardianText(i.guardian, lng)) + suiteGuardianHint([i], slug, lng));
  return parts.join(" · ");
}
// spec_finish's warnings: a recorded guardian run says dev-guardian should be updated (older than GUARDIAN_MIN_VERSION, no version
// reported, a package it could not load). → [the localized line] | []
function guardianWarnings(items, lng) {
  const g = (items || []).find((i) => isRecord(i.guardian) && i.guardian.update && isGuardianCheck(i.name, i.command));
  return g ? [i18n.msg(lng).guardian.update(g.guardian.tool || null)] : [];
}

// --- the approval guard's dev-guardian rules (guards.js calls them; with a guardian check set — guardianGuardOn) -------------------
// .specs/guardian.cjs is code the gate runs and .guardian/baseline.json what it accepts as known: an agent's write of either is a
// guard-down, like removing the check — settings "guardian-launcher" / "guardian-baseline". So is an agent-run `baseline update`
// (the launcher's or dev-guardian's own: it accepts every current finding, the feature's included — "guardian-baseline-update") and
// a run of the gate (the launcher, or dev-spec's finish --run) under a DEV_GUARDIAN_CLI / CLAUDE_CONFIG_DIR the command sets itself
// ("guardian-cli": another dev-guardian would answer). No dev-spec command makes them: the user does (approvalCommand: none).
const RE_GUARDIAN_LAUNCHER_PATH = /(?:^|\/)\.specs\/+guardian\.cjs$/i;
const RE_GUARDIAN_BASELINE_PATH = /(?:^|\/)\.guardian\/+baseline\.json$/i;
// A path as approvalPathText reads it (forward slashes, `.` / `..` folded) → { setting } | null.
function guardianGuardedFile(t) {
  if (RE_GUARDIAN_LAUNCHER_PATH.test(t)) return { setting: "guardian-launcher" };
  if (RE_GUARDIAN_BASELINE_PATH.test(t)) return { setting: "guardian-baseline" };
  return null;
}
const RE_GUARDIAN_PROGRAM = /(?:^|\/)(?:guardian\.cjs|dev-guardian(?:\.mjs)?)$/i;
const RE_GUARDIAN_ENV = /^(?:DEV_GUARDIAN_CLI|CLAUDE_CONFIG_DIR)=/i;
// One simple command's words → its dev-guardian guard-downs. prog: the index of the program it runs (guards.js programAt — past
// node and the other launchers), devSpecAt: the CLI's script (devSpecWordAt) or -1; ctx.vars: the variables the command set before it.
function guardianShellActions(words, prog, devSpecAt, ctx) {
  const out = [];
  const runsGuardian = prog >= 0 && RE_GUARDIAN_PROGRAM.test(String(words[prog]).replace(/\\/g, "/"));
  if (runsGuardian && /^baseline$/i.test(words[prog + 1] || "") && /^update$/i.test(words[prog + 2] || "")) {
    out.push({ kind: "guard-down", setting: "guardian-baseline-update", source: "shell" });
  }
  const finishRun = devSpecAt >= 0 && /^finish$/i.test(words.slice(devSpecAt + 1).find((w) => !w.startsWith("-")) || "") && words.includes("--run");
  if (runsGuardian || finishRun) {
    const at = runsGuardian ? prog : devSpecAt;
    const vars = ctx && ctx.vars ? ctx.vars : {};
    const has = (k) => Object.prototype.hasOwnProperty.call(vars, k);
    if (words.slice(0, at).some((w) => RE_GUARDIAN_ENV.test(w)) || has("dev_guardian_cli") || has("claude_config_dir")) {
      out.push({ kind: "guard-down", setting: "guardian-cli", source: "shell" });
    }
  }
  return out;
}
// Does the project run dev-guardian's gate — so its guard rules apply? meta: roadmap.json's meta; unknown (a broken roadmap.json) →
// yes (fail closed, as every other guard-down).
function guardianGuardOn(meta) {
  if (!isObj(meta)) return true;
  return isObj(meta.checks) && Object.entries(meta.checks).some(([n, c]) => typeof c === "string" && isGuardianCheck(n, c));
}
// The approval guard's actions without the dev-guardian ones when the project runs no gate (they guard nothing then).
const guardianGuardFilter = (actions, meta) => (guardianGuardOn(meta) ? actions : actions.filter((a) => !/^guardian-/.test(String(a.setting || ""))));


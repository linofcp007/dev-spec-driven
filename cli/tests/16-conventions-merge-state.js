"use strict";
// git's merge driver for the spec state (1.21 F1a) — merge-state on three files, --install / --uninstall, a real two-branch merge.

const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

exports.run = ({ ok, run, tmp, CLI }) => {
  const js = JSON.stringify;
  const parse = (f) => { try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch { return null; } };
  const jsonOf = (r) => { try { return JSON.parse(r.out); } catch { return null; } };

  // --- merge-state on three files (what git hands the driver: %O %A %B %P) — no git needed
  const d = path.join(tmp, "ms-files");
  fs.mkdirSync(d, { recursive: true });
  const put = (name, obj) => { const f = path.join(d, name); fs.writeFileSync(f, typeof obj === "string" ? obj : js(obj, null, 2) + "\n"); return f; };
  const T = (day) => new Date(Date.UTC(2026, 8, day)).toISOString();
  const sBase = { lang: "en", tracks: ["core"], approvals: { requirements: { at: T(2), by: "a" } }, approvalHistory: [{ phase: "requirements", at: T(2), by: "a" }] };
  const sOurs = { ...sBase, ticks: { 1: T(4) }, evidence: { 1: { command: "npm test", exitCode: 0, at: T(4) } } };
  const sTheirs = { ...sBase, ticks: { 2: T(5) }, evidence: { 2: { command: "npm test", exitCode: 0, at: T(5) } },
    approvals: { ...sBase.approvals, design: { at: T(5), by: "b" } }, approvalHistory: sBase.approvalHistory.concat([{ phase: "design", at: T(5), by: "b" }]) };
  const [b1, o1, t1] = [put("b1", sBase), put("o1", sOurs), put("t1", sTheirs)];
  const m1 = run(["merge-state", b1, o1, t1, ".specs/invoices/.state.json"]);
  const r1 = parse(o1);
  ok(m1.code === 0 && m1.out === "" && r1 && js(Object.keys(r1.ticks)) === '["1","2"]' && js(Object.keys(r1.evidence)) === '["1","2"]' && !!r1.approvals.design && r1.approvalHistory.length === 2 &&
    !("mergeConflicts" in r1) && /\n$/.test(fs.readFileSync(o1, "utf8")),
    "1.21 F1a: merge-state <base> <ours> <theirs> <path> merges a .state.json both branches changed (ticks, evidence, an approval) into <ours> — exit 0, silent (got " + js([m1, r1]) + ")");

  const rBase = { meta: { lang: "en" }, features: {} };
  const [b2, o2, t2] = [put("b2", rBase), put("o2", { meta: { lang: "pt" }, features: {} }), put("t2", { meta: { lang: "es" }, features: {}, backlog: [{ name: "Later" }] })];
  const m2 = run(["merge-state", b2, o2, t2, ".specs/roadmap.json"]);
  const r2 = parse(o2);
  const m2j = run(["merge-state", b2, put("o2j", { meta: { lang: "pt" } }), t2, "--kind", "roadmap", "--json"]);
  const j2 = jsonOf(m2j);
  ok(m2.code === 1 && /\.specs\/roadmap\.json: 1 conflict\(s\) — ours kept at each/.test(m2.out) && /meta\.lang: ours "pt" · theirs "es" · base "en"/.test(m2.out) &&
    r2 && r2.meta.lang === "pt" && js(r2.mergeConflicts) === '[{"path":"meta.lang","base":"en","ours":"pt","theirs":"es"}]' && r2.backlog[0].name === "Later" &&
    m2j.code === 1 && j2 && j2.ok === true && j2.clean === false && j2.kind === "roadmap" && j2.conflicts.length === 1,
    "1.21 F1a: a real conflict (a meta scalar both branches set differently) exits 1 and stays READABLE — valid JSON, ours kept, the conflict listed under mergeConflicts and on stderr; --json prints the result (got " + js([m2, r2, j2]) + ")");

  const o3 = put("o3", sOurs);
  const before3 = fs.readFileSync(o3, "utf8");
  const m3 = run(["merge-state", b1, o3, put("t3", "{ \"lang\": "), ".specs/x/.state.json"]);
  const gen = "# Roadmap\n\n<!-- AUTO-GENERATED by dev-spec — edits are overwritten -->\n";
  const o4 = put("o4.md", gen + "ours\n");
  const m4 = run(["merge-state", put("b4.md", gen), o4, put("t4.md", gen + "theirs\n"), ".specs/ROADMAP.md"]);
  const m5 = run(["merge-state", b1, o1]);
  ok(m3.code === 1 && /theirs is not valid JSON/.test(m3.out) && fs.readFileSync(o3, "utf8") === before3 &&
    m4.code === 0 && fs.readFileSync(o4, "utf8") === gen + "ours\n" && m5.code === 1 && /usage: dev-spec merge-state <base> <ours> <theirs>/.test(m5.out),
    "1.21 F1a: an unparseable side merges nothing (exit 1, ours untouched); a generated ROADMAP.md both sides regenerated keeps ours (exit 0); two files is a usage error (got " + js([m3, m4.code, m5]) + ")");
  // 1.23 review (L13): with --json an unparseable side prints its refusal on stdout too ({ok: false, parseError, error}) — it printed nothing
  const m3j = spawnSync(process.execPath, [CLI, "merge-state", b1, o3, put("t3j", "{ \"lang\": "), ".specs/x/.state.json", "--json"], { encoding: "utf8", env: { ...process.env, SPEC_PROJECT_DIR: tmp } }); // the harness's run() isolation: never the language of a .specs/ above the repo's cwd
  const j3 = (() => { try { return JSON.parse(m3j.stdout); } catch { return null; } })();
  ok(m3j.status === 1 && j3 && j3.ok === false && j3.parseError === "theirs" && /theirs is not valid JSON/.test(j3.error) && fs.readFileSync(o3, "utf8") === before3,
    "1.23 review: merge-state --json on an unparseable side prints {ok: false, parseError, error} on stdout, exit 1, ours untouched (got " + js([m3j.status, m3j.stdout.slice(0, 160)]) + ")");
  // 1.24 r6 E5: two branches each adding one dependency edge that together close a cycle — the merge exited 0 (clean) and wrote the
  // cycle; it is a conflict now: exit 1, ours kept at the dependsOn that closes it, the conflict listed
  const cBase = { meta: { lang: "en" }, features: { alpha: {}, beta: {} } };
  const [b8, o8, t8] = [put("b8", cBase), put("o8", { ...cBase, features: { alpha: { dependsOn: ["beta"] }, beta: {} } }), put("t8", { ...cBase, features: { alpha: {}, beta: { dependsOn: ["alpha"] } } })];
  const m8 = run(["merge-state", b8, o8, t8, ".specs/roadmap.json"]);
  const r8 = parse(o8);
  ok(m8.code === 1 && /features\.beta\.dependsOn/.test(m8.out) && r8 && js(r8.features.alpha.dependsOn) === '["beta"]' && !r8.features.beta.dependsOn &&
    Array.isArray(r8.mergeConflicts) && r8.mergeConflicts[0].path === "features.beta.dependsOn",
    "1.24 r6 E5: merge-state on roadmap.json whose two sides' dependency edges close a cycle exits 1 — ours kept at the edge that closes it, the conflict listed (got " + js([m8.code, m8.out, r8]) + ")");

  // --- with git: --install / --uninstall, then a real merge of two branches (skipped without git — the Docker images have it)
  const git = (cwd, ...args) => spawnSync("git", args, { cwd, encoding: "utf8", env: { ...process.env, GIT_TERMINAL_PROMPT: "0" } });
  const hasGit = (() => { try { const g = git(tmp, "--version"); return !g.error && g.status === 0; } catch { return false; } })();
  if (!hasGit) return;

  // 1.23 review (L13): a hand-written overview goes to git merge-file — with --json its result is printed (it printed nothing)
  const hw = "# Roadmap (by hand)\n\nline a\nline b\nline c\nline d\nline e\n";
  const o6 = put("o6.md", hw.replace("line a", "line a (ours)")), o7 = put("o7.md", hw.replace("line a", "line a (ours)"));
  const m6 = spawnSync(process.execPath, [CLI, "merge-state", put("b6.md", hw), o6, put("t6.md", hw.replace("line e", "line e (theirs)")), ".specs/ROADMAP.md", "--json"], { encoding: "utf8" });
  const m7 = spawnSync(process.execPath, [CLI, "merge-state", put("b7.md", hw), o7, put("t7.md", hw.replace("line a", "line a (theirs)")), ".specs/ROADMAP.md", "--json"], { encoding: "utf8" });
  const j6 = (() => { try { return JSON.parse(m6.stdout); } catch { return null; } })(), j7 = (() => { try { return JSON.parse(m7.stdout); } catch { return null; } })();
  ok(m6.status === 0 && j6 && j6.ok === true && j6.merged === "text" && j6.clean === true && /line a \(ours\)[\s\S]*line e \(theirs\)/.test(fs.readFileSync(o6, "utf8")) &&
    m7.status === 1 && j7 && j7.ok === true && j7.clean === false && j7.conflicts >= 1 && /<<<<<<< ours/.test(fs.readFileSync(o7, "utf8")),
    "1.23 review: merge-state --json on a hand-written overview prints git merge-file's result ({merged: 'text', clean, conflicts}); exit 0 clean, 1 with conflict markers (got " + js([m6.status, j6, m7.status, j7]) + ")");

  const outside = path.join(tmp, "ms-no-repo");
  fs.mkdirSync(outside, { recursive: true });
  const noRepo = git(outside, "rev-parse", "--git-dir").status !== 0; // tmp may sit inside a repository — then skip this one
  const iNo = noRepo ? run(["merge-state", "--install", "--project", outside]) : { code: 1, out: "is not inside a git repository" };

  const repo = path.join(tmp, "ms-repo");
  fs.mkdirSync(repo, { recursive: true });
  git(repo, "init", "-q");
  for (const [k, v] of [["user.email", "t@example.com"], ["user.name", "Test"], ["commit.gpgsign", "false"], ["core.autocrlf", "false"], ["core.hooksPath", path.join(tmp, "ms-no-hooks")]]) git(repo, "config", k, v);
  fs.writeFileSync(path.join(repo, ".gitattributes"), "*.png binary\n");
  const i1 = run(["merge-state", "--install", "--project", repo]);
  const i2 = jsonOf(run(["merge-state", "--install", "--json", "--project", repo]));
  const attrs = fs.readFileSync(path.join(repo, ".gitattributes"), "utf8");
  const drv = git(repo, "config", "merge.dev-spec-state.driver").stdout.trim();
  const cliPosix = path.resolve(CLI).replace(/\\/g, "/");
  const u1 = run(["merge-state", "--uninstall", "--project", repo]);
  const attrsU = fs.readFileSync(path.join(repo, ".gitattributes"), "utf8");
  const drvU = git(repo, "config", "merge.dev-spec-state.driver");
  ok(iNo.code === 1 && /is not inside a git repository/.test(iNo.out) && i1.code === 0 && /\.gitattributes: the merge driver's lines added/.test(i1.out) && /every teammate runs node "[^"]+\/cli\/dev-spec\.js" merge-state --install once — and again after each plugin update/.test(i1.out) &&
    attrs.startsWith("*.png binary\n") && /^\.specs\/\*\*\/\.state\.json merge=dev-spec-state$/m.test(attrs) && /^\.specs\/roadmap\.json merge=dev-spec-state$/m.test(attrs) &&
    drv === "node '" + cliPosix + "' merge-state %O %A %B %P" && i2 && i2.ok === true && i2.attributes.changed === false && i2.config.length === 2 &&
    u1.code === 0 && /the merge driver's lines removed/.test(u1.out) && attrsU === "*.png binary\n" && drvU.status !== 0,
    "1.21 F1a: merge-state --install writes the .gitattributes lines (other lines kept, idempotent) and this clone's git config (merge.dev-spec-state.driver = node '<clone>/cli/dev-spec.js' merge-state %O %A %B %P); --uninstall removes both; outside a repository it refuses (got " +
    js([iNo.out.slice(0, 120), i1.out.slice(0, 300), drv, u1.out.slice(0, 200)]) + ")");

  // 1.24 r6 B9: --uninstall outside a repository said what --install writes — it names --uninstall (nothing to remove there)
  {
    const uNo = noRepo ? run(["merge-state", "--uninstall", "--project", outside]) : null;
    ok(!uNo || (uNo.code === 1 && /is not inside a git repository/.test(uNo.out) && /merge-state --uninstall/.test(uNo.out) && !/--install/.test(uNo.out)),
      "1.24 r6 B9: merge-state --uninstall outside a git repository exits 1 naming --uninstall, not --install" + (uNo ? " (got " + js(uNo.out.trim().slice(0, 200)) + ")" : " — skipped: tmp sits inside a repository"));
  }

  // 1.25.1 (review 7): --install / --uninstall never write through a .gitattributes that is a link (a cloned repository's) — it wrote
  // the driver's lines into the file it pointed at — nor over a folder of that name: refused (exit 1, code attributes-not-file), the
  // target untouched, no git config written
  {
    const lr = path.join(tmp, "ms-link-repo");
    fs.mkdirSync(lr, { recursive: true });
    git(lr, "init", "-q");
    const victim = path.join(tmp, "ms-link-victim.txt");
    fs.writeFileSync(victim, "keep me\n");
    let linked = true;
    try { fs.symlinkSync(victim, path.join(lr, ".gitattributes"), "file"); } catch { linked = false; }
    const li = linked ? jsonOf(run(["merge-state", "--install", "--json", "--project", lr])) : null;
    const lu = linked ? run(["merge-state", "--uninstall", "--project", lr]) : null;
    const fr = path.join(tmp, "ms-dir-repo");
    fs.mkdirSync(path.join(fr, ".gitattributes"), { recursive: true });
    git(fr, "init", "-q");
    const fi = run(["merge-state", "--install", "--project", fr]);
    const cfg = git(lr, "config", "--get", "merge.dev-spec-state.driver");
    ok((!linked || (li && li.ok === false && li.code === "attributes-not-file" && lu.code === 1 && /is a link or not a regular file/.test(lu.out) &&
      fs.readFileSync(victim, "utf8") === "keep me\n" && cfg.status !== 0)) && fi.code === 1 && /is a link or not a regular file/.test(fi.out) &&
      fs.statSync(path.join(fr, ".gitattributes")).isDirectory(),
      "1.25.1 r7: merge-state --install / --uninstall refuse a .gitattributes that is a link (the file it points at untouched, no git config) or a folder — exit 1, code attributes-not-file" +
      (linked ? "" : " (a symbolic link can't be made here: that part skipped)") + " (got " + js([li, lu && lu.code, fi.code, fi.out.trim().slice(0, 120)]) + ")");
  }

  // The end-to-end merge: main approves the planning phases; branch A approves the tasks, ticks task 1 and adds a backlog item;
  // branch B ticks task 2, adds another backlog item and a dependency. With the driver installed, `git merge` is clean and the
  // spec state holds both branches' work — valid JSON, doctor happy.
  const P = ["--project", repo];
  const f = path.join(repo, ".specs", "invoice-export");
  run(["init", "core", ...P]);
  run(["create", "Invoice export", "core", ...P]);
  run(["create", "Audit log", "core", ...P]);
  const cls = path.join(f, "classification.md");
  fs.writeFileSync(cls, fs.readFileSync(cls, "utf8").split("\n").map((l) => (/^- /.test(l) ? l : l.replace(/\[[^\]]*\]/g, "filled"))).join("\n"));
  fs.writeFileSync(path.join(f, "requirements.md"), "# Feature: Invoice export\n\n## Summary\nExport invoices as CSV.\n\n### US-1 (P1 — MVP): Export\n#### Acceptance Criteria (EARS)\n" +
    "1. **US-1.AC-1** — WHEN an admin clicks Export THE SYSTEM SHALL download a CSV.\n2. **US-1.AC-2** — IF the export fails THEN THE SYSTEM SHALL show the error code.\n\n" +
    "### US-2 (P2): Schedule\n#### Acceptance Criteria (EARS)\n1. **US-2.AC-1** — WHEN a schedule is due THE SYSTEM SHALL email the CSV.\n\n" +
    "## Success Criteria\n- **SC-001** — 95% of exports finish in under 5 s.\n\n## Out of Scope\n- PDF export.\n");
  fs.writeFileSync(path.join(f, "design.md"), "# Design: Invoice export\n\n## Overview\nA nightly job and an endpoint.\n\n## Architecture\n```mermaid\ngraph TD\n  A-->B\n```\n\n## Constitution Check\n- [x] Principle 1 — complies\n");
  fs.writeFileSync(path.join(f, "tasks.md"), "# Tasks\n\n- [ ] 1. [US1] Build the CSV writer\n  - _Requirements: US-1.AC-1, US-1.AC-2_\n  - _Verify: node -e \"process.exit(0)\"_\n\n" +
    "- [ ] 2. [US2] Email the scheduled CSV\n  - _Requirements: US-2.AC-1_\n  - _Verify: node -e \"process.exit(0)\"_\n");
  const ap = ["classification", "requirements", "design"].map((ph) => run(["approve", "invoice-export", ph, "--by", "ana", ...P]));
  run(["merge-state", "--install", ...P]);
  git(repo, "add", "-A");
  git(repo, "commit", "-q", "-m", "spec: invoice export planned");
  const main = git(repo, "rev-parse", "--abbrev-ref", "HEAD").stdout.trim();
  git(repo, "checkout", "-q", "-b", "a");
  const aTasks = run(["approve", "invoice-export", "tasks", "--by", "bo", ...P]);
  const aDone = run(["done", "invoice-export", "1", "--run", ...P]);
  run(["backlog", "add", "PDF export", "later", ...P]);
  git(repo, "add", "-A");
  git(repo, "commit", "-q", "-m", "a: tasks approved, task 1");
  git(repo, "checkout", "-q", main);
  git(repo, "checkout", "-q", "-b", "b");
  const bDone = run(["done", "invoice-export", "2", "--run", ...P]);
  run(["backlog", "add", "XLSX export", ...P]);
  run(["depend", "invoice-export", "audit-log", ...P]);
  git(repo, "add", "-A");
  git(repo, "commit", "-q", "-m", "b: task 2, a dependency");
  git(repo, "checkout", "-q", "a");
  const mg = git(repo, "merge", "--no-edit", "-q", "b");
  const unmerged = git(repo, "diff", "--name-only", "--diff-filter=U").stdout.trim();
  const st = parse(path.join(f, ".state.json"));
  const rm = parse(path.join(repo, ".specs", "roadmap.json"));
  const tasksMd = fs.readFileSync(path.join(f, "tasks.md"), "utf8");
  const doc = jsonOf(run(["doctor", "invoice-export", "--json", ...P]));
  const statRun = run(["status", "invoice-export", "--json", ...P]);
  const stat = jsonOf(statRun);
  const markers = git(repo, "grep", "-l", "-e", "^<<<<<<< ", "--", ".specs").stdout.trim();
  ok(ap.every((r) => r.code === 0) && aTasks.code === 0 && aDone.code === 0 && bDone.code === 0 && mg.status === 0 && unmerged === "" && markers === "" &&
    st && js(Object.keys(st.approvals).sort()) === '["classification","design","requirements","tasks"]' && st.evidence && st.evidence[1] && st.evidence[2] && st.ticks && st.ticks[1] && st.ticks[2] &&
    st.approvalHistory.length === 4 && !("mergeConflicts" in st) && /- \[x\] 1\./.test(tasksMd) && /- \[x\] 2\./.test(tasksMd) &&
    rm && js((rm.backlog || []).map((x) => x.name)) === '["PDF export","XLSX export"]' && js(rm.features["invoice-export"].dependsOn) === '["audit-log"]' && !("mergeConflicts" in rm) &&
    doc && doc.ok === true && !doc.checks.some((c) => c.id === "merge-conflicts" || c.status === "fail") && stat && stat.tasks && stat.tasks.done === 2,
    "1.21 F1a end to end: two branches — one approves the tasks and ticks task 1, the other ticks task 2 — plus a backlog item each and a dependency merge CLEANLY with the driver installed (no conflict, no marker): .state.json and roadmap.json hold both branches' work, valid JSON, doctor happy (got " +
    js([mg.status, mg.stderr, unmerged, st && Object.keys(st.approvals), st && Object.keys(st.evidence || {}), rm && rm.backlog, doc && doc.checks.filter((c) => c.status === "fail"), stat ? stat.tasks.done : statRun.out.slice(0, 300)]) + ")");

  // 1.21 review A3 — merge-state --check (read-only, git config --get): exit 0 while the driver runs THIS clone's CLI; 1 once it runs a
  // script that no longer exists (a plugin update moved the versioned folder) or another copy, or .gitattributes names the driver and
  // this clone has none; the SessionStart hook adds its one line meanwhile. Outside a repository → 1; nothing named → 0.
  const check = (...extra) => run(["merge-state", "--check", ...P, ...extra]);
  const hookJs = path.join(path.dirname(CLI), "..", "hooks", "spec-hook.js");
  const session = () => {
    const r = spawnSync(process.execPath, [hookJs], { input: js({ hook_event_name: "SessionStart", cwd: repo }), encoding: "utf8", env: { ...process.env, CLAUDE_PROJECT_DIR: repo, SPEC_PROJECT_DIR: repo } });
    try { return JSON.parse(r.stdout).hookSpecificOutput.additionalContext.split("\n").filter((l) => /merge driver/.test(l)); } catch { return []; }
  };
  const cOk = check(), cOkJ = jsonOf(check("--json")), hOk = session();
  const gone = path.join(tmp, "ms-old-plugin", "1.20.0", "cli", "dev-spec.js").replace(/\\/g, "/");
  git(repo, "config", "merge.dev-spec-state.driver", "node '" + gone + "' merge-state %O %A %B %P");
  const cGone = check(), cGoneJ = jsonOf(check("--json")), hGone = session();
  const otherCli = path.join(tmp, "ms-other-copy", "cli", "dev-spec.js");
  fs.mkdirSync(path.dirname(otherCli), { recursive: true });
  fs.writeFileSync(otherCli, "// another copy\n");
  git(repo, "config", "merge.dev-spec-state.driver", "node '" + otherCli.replace(/\\/g, "/") + "' merge-state %O %A %B %P");
  const cOther = check(), hOther = session();
  git(repo, "config", "--remove-section", "merge.dev-spec-state");
  const cNone = check(), hNone = session();
  const reinstall = run(["merge-state", "--install", ...P]);
  const cBack = check();
  const bare = path.join(tmp, "ms-repo-plain");
  fs.mkdirSync(bare, { recursive: true });
  git(bare, "init", "-q");
  const cPlain = jsonOf(run(["merge-state", "--check", "--json", "--project", bare]));
  const cNoRepo = noRepo ? run(["merge-state", "--check", "--project", outside]) : { code: 1 };
  const cUsage = run(["merge-state", "--check", "x", ...P]);
  ok(cOk.code === 0 && /installed and runs this clone's CLI/.test(cOk.out) && cOkJ && cOkJ.status === "ok" && cOkJ.current === true && cOkJ.named === true && hOk.length === 0 &&
    cGone.code === 1 && cGone.out.includes(gone) && /which no longer exists/.test(cGone.out) && /merge-state --install/.test(cGone.out) && cGoneJ && cGoneJ.status === "missing" && cGoneJ.script === gone &&
    hGone.length === 1 && hGone[0].includes(gone) &&
    cOther.code === 1 && /not from this clone's CLI/.test(cOther.out) && hOther.length === 1 &&
    cNone.code === 1 && /names the dev-spec-state merge driver, but this clone's git config has none/.test(cNone.out) && hNone.length === 0 &&
    reinstall.code === 0 && cBack.code === 0 && cPlain && cPlain.status === "none" && cNoRepo.code === 1 && cUsage.code === 1 && /--check/.test(cUsage.out),
    "1.21 review A3: merge-state --check exits 0 while git's driver runs this clone's CLI and 1 when it runs a missing script (a plugin update) or another copy, or when .gitattributes names the driver and the clone has none — naming the path and the re-install line; the SessionStart hook adds one line for the missing / other script only; re-running --install fixes it (got " +
    js([cOk.out, cGone.out, cOther.out, cNone.out, hGone, hOther, cPlain, cUsage.out.slice(0, 160)]) + ")");
};
